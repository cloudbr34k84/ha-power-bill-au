def _plan_from_dict(data: dict[str, Any], effective_from: date) -> Plan:
    import_schedule = Schedule(Band(**b) for b in data[CONF_IMPORT_BANDS])
    export_schedule = None
    if data.get(CONF_EXPORT_BANDS):
        export_schedule = Schedule(Band(**b) for b in data[CONF_EXPORT_BANDS])
    return Plan(
        effective_from=effective_from,
        import_schedule=import_schedule,
        export_schedule=export_schedule,
        daily_supply=float(data[CONF_DAILY_SUPPLY]),
        daily_membership=float(data[CONF_DAILY_MEMBERSHIP]),
        rates_include_gst=bool(data[CONF_RATES_INCLUDE_GST]),
        export_daily_cap=float(data.get("export_daily_cap", 0.0)),
        export_over_cap_rate=float(data.get("export_over_cap_rate", 0.0)),
        demand_rate=float(data.get("demand_rate", 0.0)),
        demand_kw={str(k): float(v) for k, v in (data.get("demand_kw") or {}).items()},
        demand_estimate=bool(data.get("demand_estimate", False)),
        demand_window_start=int(data.get("demand_window_start", 16)),
        demand_window_end=int(data.get("demand_window_end", 21)),
        demand_block_minutes=int(data.get("demand_block_minutes", 30)),
    )


def build_timeline(cfg: dict[str, Any]) -> Timeline:
    """Plans from config. `plans` (a list of dated plans) is used when present, otherwise the
    single current plan is the whole timeline. Raises ValueError if any plan is invalid."""
    if cfg.get(CONF_PLANS):
        plans = [
            _plan_from_dict(p, date.fromisoformat(p["effective_from"]))
            for p in cfg[CONF_PLANS]
        ]
    else:
        plans = [_plan_from_dict(cfg, LEGACY_START)]
    if cfg.get(CONF_EXPORT_ENTITY) and any(p.export_schedule is None for p in plans):
        raise ValueError("missing_export_bands")
    return Timeline(plans)


class TariffRuntime:
    """Owns the ledger and the state listeners for one config entry."""

    def __init__(
        self,
        hass: HomeAssistant,
        entry: ConfigEntry[TariffRuntime],
        store: Store[dict[str, Any]],
    ) -> None:
        cfg = {**entry.data, **entry.options}
        self.hass = hass
        self.entry_id = entry.entry_id
        self._store = store
        self.timeline = build_timeline(cfg)
        self.import_entity: str = cfg[CONF_IMPORT_ENTITY]
        self.export_entity: str | None = cfg.get(CONF_EXPORT_ENTITY) or None
        self.device_entities: list[str] = list(cfg.get(CONF_TRACKED_DEVICES) or [])
        # Solar-share pricing needs both the export meter and solar production.
        self.solar_entity: str | None = cfg.get(CONF_SOLAR_ENTITY) or None
        self.solar_mode = bool(self.solar_entity and self.export_entity)
        # Device and untracked usage is priced for every hour before this (UTC).
        self._settled_through: datetime | None = None
        self._saved_settled_through: datetime | None = None
        self._settle_from: dict[str, datetime] = {}
        # UTC hours the import meter was offline in: True while it is still offline,
        # False once a reading arrived after the outage in the same hour.
        self._import_gaps: dict[str, bool] = {}
        # kWh and cost devices were charged at the full rate during a long outage, to
        # take off the import that arrives when the meter returns.
        self._forced: list[float] = [0.0, 0.0]
        self.ledger = UsageLedger()
        self._unsubs: list[Callable[[], None]] = []
        self._history_start = dt_util.now().date()
        self._stored_ledger: UsageLedger | None = None
        self._demand_lock = asyncio.Lock()
        self._stopping = False
        self._pending_energy: dict[str, dict[str, float]] = {}
        self._history_watermarks: dict[str, datetime] = {}

        # entity_id -> (ledger source key, pricer for that source's readings)
        self._sources: dict[
            str, tuple[str, Callable[[datetime], tuple[str, float]]]
        ] = {self.import_entity: ("import", self._import_price)}
        if self.export_entity:
            self._sources[self.export_entity] = ("export", self._export_price)
        self._device_sensor_keys: dict[str, str] = {}
        for device in self.device_entities:
            record = source_record(entry.data, device)
            self._device_sensor_keys[device] = record.get("sensor_key") or (
                f"device_{device.split('.', 1)[-1]}"
            )
            ledger_key = record.get("ledger_key") or device
            self._sources.setdefault(device, (ledger_key, self._import_price))
        self._device_keys = {
            key
            for entity, (key, _pricer) in self._sources.items()
            if entity in self.device_entities
        }

    def _import_price(self, when: datetime) -> tuple[str, float]:
        plan = self.timeline.plan_on(when.date())
        band = plan.import_schedule.band_at(when.hour)
        return band.name, band.rate * plan.import_factor

    def _export_price(self, when: datetime) -> tuple[str, float]:
        plan = self.timeline.plan_on(when.date())
        assert plan.export_schedule is not None  # Validated by build_timeline.
        band = plan.export_schedule.band_at(when.hour)
        return band.name, band.rate

    async def async_start(self) -> None:
        """Rebuild the ledger from HA's own statistics, then listen for live readings.

        The recorder's hourly statistics are the source of truth for history, so every setup
        rebuilds the ledger from them. Plan changes therefore reprice the whole history.
        """
        now = dt_util.now()
        self.ledger = UsageLedger()
        stored = await self._store.async_load()
        if isinstance(stored, dict):
            try:
                if "history_start" in stored:
                    self._history_start = min(
                        date.fromisoformat(stored["history_start"]), now.date()
                    )
                    self._stored_ledger = UsageLedger(stored)
                    self._load_pending(stored.get("pending_energy", {}), now)
                    self._load_solar_progress(stored, now)
                signatures = set(str(stored.get("demand_signature", "")).split("|"))
                peaks = UsageLedger(
                    {"demand_peaks": stored.get("demand_peaks", {})}
                ).demand_peaks
                for month, peak in peaks.items():
                    at = dt_util.parse_datetime(str(peak["at"]))
                    if at is None or at.tzinfo is None or at > now:
                        continue
                    plan = self.timeline.plan_on(dt_util.as_local(at).date())
                    signature = f"{plan.effective_from}:{plan.demand_window_start}-{plan.demand_window_end}/{plan.demand_block_minutes}"
                    if plan.demand_estimate and signature in signatures:
                        self.ledger.demand_peaks[month] = peak
            except (AttributeError, TypeError, ValueError, KeyError, OverflowError):
                _LOGGER.warning(
                    "Ignoring invalid saved tariff data; rebuilding from recorder statistics"
                )
                self._history_start = now.date()
                self._stored_ledger = None
        recorder_ready = "recorder" in self.hass.config.components
        if self._estimating:
            if recorder_ready:
                await self._async_scan_demand(DEMAND_SCAN_DAYS, reprice=False)
        if recorder_ready:
            await self._async_backfill(now)
            self._replay_pending()
        elif self._stored_ledger is not None:
            peaks = self.ledger.demand_peaks
            self.ledger = self._stored_ledger
            self.ledger.demand_peaks = peaks
        # live baseline: readings from now on are added as they change
        for entity, (key, _pricer) in self._watched().items():
            value = energy_value(self.hass.states.get(entity))
            if value is not None:
                self.ledger.last_seen[key] = value
        if self.solar_mode:
            if not self._settle_from:  # No recorder: continue from the saved ledger.
                resume = self._saved_settled_through or _hour_floor(
                    now.astimezone(dt_util.UTC)
                )
                self._settle_from = dict.fromkeys(
                    (*self._device_keys, UNTRACKED_KEY), resume
                )
            self._settled_through = min(self._settle_from.values())
            self._settle(now)
        self._ensure_today(now.date())
        self.ledger.prune(now.date())
        self._unsubs.append(
            async_track_state_change_event(
                self.hass, list(self._watched()), self._on_source_change
            )
        )
        self._unsubs.append(
            async_track_time_interval(self.hass, self._on_tick, timedelta(minutes=1))
        )
        if self._estimating and recorder_ready:
            self._unsubs.append(
                async_track_time_interval(
                    self.hass, self._on_demand_tick, DEMAND_REFRESH
                )
            )
        self._store.async_delay_save(self._snapshot, SAVE_DELAY_SECONDS)

    async def _async_backfill(self, now: datetime) -> None:
        """Rebuild available meter history without installation-specific date boundaries."""
        ids = set(self._sources)
        if self.solar_mode:
            ids.add(self.solar_entity)
        recorder = get_instance(self.hass)

        def fetch(
            period: str, t0: datetime, t1: datetime
        ) -> dict[str, list[dict[str, Any]]]:
            return _statistics_result(
                statistics_during_period(
                    self.hass,
                    t0.astimezone(dt_util.UTC),
                    t1.astimezone(dt_util.UTC),
                    ids,
                    period,
                    {"energy": "Wh"},
                    {"change"},  # Wh for every sensor, whatever its native unit
                )
            )

        daily = await recorder.async_add_executor_job(fetch, "day", HISTORY_EPOCH, now)
        hourly = await recorder.async_add_executor_job(
            fetch, "hour", HISTORY_EPOCH, now
        )
        await self.hass.async_add_executor_job(self._build_history, daily, hourly, now)

    def _build_history(
        self,
        daily: dict[str, list[dict[str, Any]]],
        hourly: dict[str, list[dict[str, Any]]],
        now: datetime,
    ) -> None:
        """Build history in an executor before live subscriptions are registered."""

        def valid_rows(
            rows: list[dict[str, Any]], limit: float
        ) -> list[tuple[datetime, float]]:
            return _valid_rows(rows, limit, now)

        deferred: dict[
            str,
            tuple[
                list[tuple[datetime, float]],
                list[tuple[datetime, float]],
                Callable[[datetime], tuple[str, float]],
            ],
        ] = {}
        first_import: date | None = None
        for entity, (key, pricer) in self._sources.items():
            capped_days: dict[
                date, float
            ] = {}  # export on plans with a daily cap, booked per day
            hour_rows = valid_rows(hourly.get(entity, []), MAX_HOURLY_KWH)
            hourly_days = {when.date() for when, _ in hour_rows}
            day_rows = [
                row
                for row in valid_rows(daily.get(entity, []), MAX_DAILY_KWH)
                if row[0].date() not in hourly_days
            ]
            if key == "import" and (rows := hour_rows + day_rows):
                first_import = min(when.date() for when, _ in rows)
            if not hour_rows and not day_rows:
                _LOGGER.debug(
                    "No recorder rows for a configured energy source; using saved readings when available"
                )
            if not hour_rows and not day_rows and self._stored_ledger is not None:
                if key in self._stored_ledger.days:
                    self.ledger.days[key] = self._stored_ledger.days[key]
                if key in self._stored_ledger.totals:
                    self.ledger.totals[key] = self._stored_ledger.totals[key]
                continue
            ends = [
                when.astimezone(dt_util.UTC) + timedelta(hours=1)
                for when, _ in hour_rows
            ]
            ends.extend(
                datetime.combine(
                    when.date() + timedelta(days=1),
                    datetime.min.time(),
                    tzinfo=now.tzinfo,
                ).astimezone(dt_util.UTC)
                for when, _ in day_rows
            )
            if ends:
                self._history_watermarks[key] = max(ends)
            if self.solar_mode and key in self._device_keys:
                # Priced below, once the grid share of every hour is known.
                deferred[key] = (hour_rows, day_rows, pricer)
                continue
            hours = []
            for when, change in hour_rows:
                plan = self.timeline.plan_on(when.date())
                if key == "export" and plan.export_daily_cap > 0:
                    capped_days[when.date()] = (
                        capped_days.get(when.date(), 0.0) + change
                    )
                    continue
                hours.append((when, change))
            book_hourly(self.ledger, key, hours, pricer)
            # Use daily-only history at the noon rate when no hourly detail exists.
            for day_start, change in day_rows:
                plan = self.timeline.plan_on(day_start.date())
                if key == "export" and plan.export_daily_cap > 0:
                    capped_days[day_start.date()] = (
                        capped_days.get(day_start.date(), 0.0) + change
                    )
                    continue
                _name, price = pricer(day_start.replace(hour=12))
                self.ledger.add_energy(key, day_start.date(), _name, change, price)
            for day, total in capped_days.items():
                book_export_day(
                    self.ledger, key, day, total, self.timeline.plan_on(day)
                )
        if self.solar_mode:
            self._allocate_history(daily, hourly, deferred, now)
        if first_import is not None:
            self._history_start = first_import
        elif self._stored_ledger is not None:
            _LOGGER.debug(
                "No import history available; restoring the saved tariff ledger"
            )
            self.ledger.fixed_days = self._stored_ledger.fixed_days
            if FIXED_KEY in self._stored_ledger.totals:
                self.ledger.totals[FIXED_KEY] = self._stored_ledger.totals[FIXED_KEY]
            self.ledger.ensure_fixed_through(now.date(), self._daily_charge)
            self.ledger.reprice_fixed_days(
                {day[:7] for day in self.ledger.fixed_days}, self._daily_charge
            )
            return
        else:
            _LOGGER.debug(
                "No import history available; fixed charges start on the initial setup day"
            )
        book_fixed_range(
            self.ledger, self._history_start, now.date(), self._daily_charge
        )

    def _load_pending(
        self, pending: dict[str, dict[str, float]], now: datetime
    ) -> None:
        """Load a bounded buffer of live increments not yet covered by recorder."""
        if not isinstance(pending, dict):
            return
        allowed = {key for key, _ in self._watched().values()}
        cutoff = now.astimezone(dt_util.UTC) - PENDING_RETENTION
        for source, slots in pending.items():
            if source not in allowed or not isinstance(slots, dict):
                continue
            for timestamp, amount in slots.items():
                try:
                    at = dt_util.parse_datetime(timestamp)
                    amount = float(amount)
                except (TypeError, ValueError, OverflowError):
                    continue
                if at is None or at.tzinfo is None or not cutoff <= at <= now:
                    continue
                if math.isfinite(amount) and amount >= 0:
                    self._pending_energy.setdefault(source, {})[timestamp] = amount

    def _replay_pending(self) -> None:
        """Replay increments after each source's completed recorder periods once."""
        pricers = {key: pricer for key, pricer in self._sources.values()}
        for source, slots in self._pending_energy.items():
            if source not in pricers or (
                self.solar_mode and source in self._device_keys
            ):
                continue  # Solar readings, and devices priced by `_settle`.
            watermark = self._history_watermarks.get(source)
            if watermark is None:
                continue  # This source was restored from its complete saved ledger.
            for timestamp, amount in sorted(slots.items()):
                at = dt_util.parse_datetime(timestamp)
                if at is None or at < watermark:
                    continue
                when = dt_util.as_local(at)
                plan = self.timeline.plan_on(when.date())
                if source == "export" and plan.export_daily_cap:
                    book_export_day(self.ledger, source, when.date(), amount, plan)
                else:
                    band, rate = pricers[source](when)
                    self.ledger.add_energy(source, when.date(), band, amount, rate)

    def _watched(
        self,
    ) -> dict[str, tuple[str, Callable[[datetime], tuple[str, float]] | None]]:
        """Every meter whose readings are followed: the priced sources, plus solar."""
        watched: dict[str, tuple[str, Callable[[datetime], tuple[str, float]] | None]]
        watched = dict(self._sources)
        if self.solar_mode and self.solar_entity not in watched:
            watched[self.solar_entity] = (SOLAR_KEY, None)  # type: ignore[index]
        return watched

    def _allocate_history(
        self,
        daily: dict[str, list[dict[str, Any]]],
        hourly: dict[str, list[dict[str, Any]]],
        deferred: dict[
            str,
            tuple[
                list[tuple[datetime, float]],
                list[tuple[datetime, float]],
                Callable[[datetime], tuple[str, float]],
            ],
        ],
        now: datetime,
    ) -> None:
        """Price device history at each hour's grid share, and book the untracked rest.

        History is booked up to one common hour `start`: the earliest recent watermark of
        the import meter and the devices with recorder rows. Later hours are priced live
        by `_settle` from the buffered readings, so no hour is booked twice.
        """
        now_utc = now.astimezone(dt_util.UTC)
        solar = self.solar_entity or ""
        export = self.export_entity or ""

        def by_hour(entity: str) -> dict[datetime, tuple[datetime, float]]:
            # Keyed by UTC: the local hour repeated at the end of daylight saving is two hours.
            return {
                when.astimezone(dt_util.UTC): (when, kwh)
                for when, kwh in _valid_rows(
                    hourly.get(entity, []), MAX_HOURLY_KWH, now
                )
            }

        def by_day(entity: str) -> dict[date, float]:
            return {
                when.date(): kwh
                for when, kwh in _valid_rows(daily.get(entity, []), MAX_DAILY_KWH, now)
            }

        imp_h, exp_h, sol_h = (
            by_hour(self.import_entity),
            by_hour(export),
            by_hour(solar),
        )
        imp_d, exp_d, sol_d = by_day(self.import_entity), by_day(export), by_day(solar)

        recent = now_utc - PENDING_RETENTION
        marks = [
            self._history_watermarks[key]
            for key in ("import", *deferred)
            if key in self._history_watermarks
            and self._history_watermarks[key] >= recent
        ]
        saved = self._saved_settled_through
        start = min(marks) if marks else (saved or _hour_floor(now_utc))
        # An outage still in the buffer was priced live together with the hour the meter
        # returned in: price it from the buffer again, the same way.
        outages = [
            at.astimezone(dt_util.UTC)
            for gap in self._import_gaps
            if (at := dt_util.parse_datetime(gap)) is not None
        ]
        if outages:
            start = min(start, *outages)
        # Never leave to the buffer hours it no longer holds (HA was off over a day).
        buffered = [
            _hour_floor(at.astimezone(dt_util.UTC))
            for slots in self._pending_energy.values()
            for slot in slots
            if (at := dt_util.parse_datetime(slot)) is not None
        ]
        if buffered:
            start = max(start, min(buffered))
        else:
            every = [
                self._history_watermarks[key]
                for key in ("import", *deferred)
                if key in self._history_watermarks
            ]
            start = max(start, *every) if every else start
        # Devices without recorder rows come back from the saved ledger, which already
        # holds what was priced live before the restart.
        restored = self._device_keys - set(deferred)
        restored_from = max(start, saved or _hour_floor(now_utc))
        self._settle_from = {key: start for key in deferred}
        self._settle_from.update(dict.fromkeys(restored, restored_from))

        def value(table: dict[Any, tuple[datetime, float]], at: Any) -> float:
            return table[at][1] if at in table else 0.0

        def day_share(day: date) -> float:
            if day not in imp_d:
                return 1.0  # No import reading for this day: assume the grid paid.
            return solar_split(
                imp_d[day], exp_d.get(day, 0.0), sol_d.get(day, 0.0), 0.0
            )[0]

        # Days the import meter only has a daily total for are split per day.
        daily_only = set(imp_d) - {when.date() for when, _kwh in imp_h.values()}
        device_days: dict[date, list[float]] = {}  # day -> [kWh, cost]

        def note_day(day: date, kwh: float, cost: float) -> None:
            if day in daily_only:
                cell = device_days.setdefault(day, [0.0, 0.0])
                cell[0] += kwh
                cell[1] += cost

        device_hours: dict[datetime, float] = {}
        for key, (hour_rows, day_rows, pricer) in deferred.items():
            for when, kwh in hour_rows:
                at = when.astimezone(dt_util.UTC)
                if at >= start:
                    continue  # Priced live from the buffer.
                if at in imp_h:
                    grid = solar_split(
                        imp_h[at][1], value(exp_h, at), value(sol_h, at), 0.0
                    )[0]
                elif when.date() in daily_only:
                    grid = day_share(when.date())
                else:
                    grid = 1.0  # No import reading for this hour: assume the grid paid.
                band, price = pricer(when)
                self.ledger.add_energy(key, when.date(), band, kwh, price * grid)
                device_hours[at] = device_hours.get(at, 0.0) + kwh
                note_day(when.date(), kwh, kwh * price * grid)
            for day_start, kwh in day_rows:
                if day_start.astimezone(dt_util.UTC) >= start:
                    continue
                day = day_start.date()
                grid = day_share(day)
                band, price = pricer(day_start.replace(hour=12))
                self.ledger.add_energy(key, day, band, kwh, price * grid)
                note_day(day, kwh, kwh * price * grid)

        if restored or not (imp_h or imp_d):
            # The untracked rest can't be rebuilt without every device's hourly usage:
            # keep what was booked live, and continue live from the same point.
            self._settle_from[UNTRACKED_KEY] = restored_from
            if self._stored_ledger is not None:
                for table in ("days", "totals"):
                    saved_table = getattr(self._stored_ledger, table)
                    if UNTRACKED_KEY in saved_table:
                        getattr(self.ledger, table)[UNTRACKED_KEY] = saved_table[
                            UNTRACKED_KEY
                        ]
            return
        self._settle_from[UNTRACKED_KEY] = start
        for at, (when, imported) in imp_h.items():
            if at >= start:
                continue
            grid, rest = solar_split(
                imported, value(exp_h, at), value(sol_h, at), device_hours.get(at, 0.0)
            )
            if rest > 0:
                band, price = self._import_price(when)
                self.ledger.add_energy(
                    UNTRACKED_KEY, when.date(), band, rest, price * grid
                )
        for day in daily_only:
            noon = dt_util.start_of_local_day(day).replace(hour=12)
            if noon.astimezone(dt_util.UTC) >= start:
                continue
            devices_kwh, devices_cost = device_days.get(day, [0.0, 0.0])
            _grid, rest = solar_split(
                imp_d[day], exp_d.get(day, 0.0), sol_d.get(day, 0.0), devices_kwh
            )
            if rest > 0:
                # The import on this day was priced at the noon rate: untracked gets
                # what is left of that after the devices.
                band, price = self._import_price(noon)
                cost = max(imp_d[day] * price - devices_cost, 0.0)
                self.ledger.add_energy(UNTRACKED_KEY, day, band, rest, cost / rest)

    def _settle(self, now: datetime) -> bool:
        """Price device and untracked usage of every finished hour.

        Readings are buffered in the slot they arrive in, so an hour is complete once it
        has ended (plus a short delay). An hour in which the import meter was offline is
        held and priced together with the hour its readings return in, because that hour
        carries the import the meter missed. Returns whether anything was booked.
        """
        if not self.solar_mode or self._settled_through is None:
            return False
        now_utc = now.astimezone(dt_util.UTC)
        cutoff = now_utc - SETTLE_DELAY
        slots: dict[datetime, dict[datetime, dict[str, float]]] = {}
        for key in (*self._device_keys, "import", "export", SOLAR_KEY):
            for slot, kwh in self._pending_energy.get(key, {}).items():
                at = dt_util.parse_datetime(slot)
                if at is None:
                    continue
                at = at.astimezone(dt_util.UTC)
                hour = _hour_floor(at)
                if hour >= self._settled_through:
                    cell = slots.setdefault(hour, {}).setdefault(at, {})
                    cell[key] = cell.get(key, 0.0) + kwh
        booked = False
        group: list[datetime] = []
        hour = self._settled_through
        while hour + HOUR <= cutoff:
            group.append(hour)
            outage = self._import_gaps.get(hour.isoformat(), False)
            # A gap is held for the meter to return, unless the buffer would expire first.
            if outage and group[0] > now_utc - PENDING_RETENTION + 2 * HOUR:
                hour += HOUR
                continue
            self._book_hours(group, slots, grid_known=not outage)
            booked = True
            hour += HOUR
            group = []
            self._settled_through = hour
        for gap in list(self._import_gaps):
            at = dt_util.parse_datetime(gap)
            if at is None or at < now_utc - PENDING_RETENTION:
                del self._import_gaps[gap]
        return booked

    def _book_hours(
        self,
        hours: list[datetime],
        slots: dict[datetime, dict[datetime, dict[str, float]]],
        *,
        grid_known: bool,
    ) -> None:
        """Book one hour, or an outage plus the hour the import meter came back in.

        Each slot is priced at its own local tariff band (a UTC hour can span two bands
        where the time zone is offset by half an hour). Untracked usage gets exactly what
        is left of the import cost booked for the same slots, so the parts add up.
        """
        cells = sorted(
            (at, cell) for hour in hours for at, cell in slots.get(hour, {}).items()
        )

        def total(key: str) -> float:
            return sum(cell.get(key, 0.0) for _at, cell in cells)

        def priced(key: str) -> list[tuple[datetime, str, float, float]]:
            """(local time, band, price, kWh) per slot this key is priced live for."""
            since = self._settle_from.get(key, hours[0])
            rows = []
            for at, cell in cells:
                kwh = cell.get(key, 0.0)
                if kwh > 0 and _hour_floor(at) >= since:
                    when = dt_util.as_local(at)
                    band, price = self._import_price(when)
                    rows.append((when, band, price, kwh))
            return rows

        devices = {key: total(key) for key in self._device_keys}
        if not grid_known:
            # Import unknown: never assume solar paid. Remember what the devices paid,
            # because the import lump that arrives later also covers these hours.
            for key in self._device_keys:
                for when, band, price, kwh in priced(key):
                    self.ledger.add_energy(key, when.date(), band, kwh, price)
                    self._forced[0] += kwh
                    self._forced[1] += kwh * price
            return
        forced_kwh, forced_cost = self._forced
        self._forced = [0.0, 0.0]
        grid, rest = solar_split(
            max(total("import") - forced_kwh, 0.0),
            total("export"),
            total(SOLAR_KEY),
            sum(devices.values()),
        )
        import_cost = 0.0
        for at, cell in cells:
            if (kwh := cell.get("import", 0.0)) > 0:
                import_cost += kwh * self._import_price(dt_util.as_local(at))[1]
        device_cost = 0.0
        for key in self._device_keys:
            for when, band, price, kwh in priced(key):
                self.ledger.add_energy(key, when.date(), band, kwh, price * grid)
                device_cost += kwh * price * grid
        last = hours[-1]
        if rest > 0 and last >= self._settle_from.get(UNTRACKED_KEY, hours[0]):
            when = dt_util.as_local(last)
            band, _price = self._import_price(when)
            cost = max(import_cost - forced_cost - device_cost, 0.0)
            self.ledger.add_energy(UNTRACKED_KEY, when.date(), band, rest, cost / rest)

    def _note_import(self, when: datetime, *, online: bool) -> None:
        """Record an import outage, or the meter reporting again in an outage hour."""
        hour = _hour_floor(when.astimezone(dt_util.UTC)).isoformat()
        if not online:
            self._import_gaps[hour] = True
        elif hour in self._import_gaps:
            self._import_gaps[hour] = False

    @property
    def device_pricing(self) -> str:
        """How tracked devices are priced: at the grid share, or at the full import rate."""
        return "solar_share" if self.solar_mode else "import_rate"

    def _remember_increment(self, source: str, when: datetime, amount: float) -> None:
        """Aggregate live increments into five-minute buckets, bounded to one day."""
        if amount <= 0:
            return
        at = when.astimezone(dt_util.UTC)
        slot = at.replace(
            minute=at.minute // 5 * 5, second=0, microsecond=0
        ).isoformat()
        slots = self._pending_energy.setdefault(source, {})
        slots[slot] = slots.get(slot, 0.0) + amount
        self._prune_pending(when)

    def _prune_pending(self, now: datetime) -> None:
        cutoff = now.astimezone(dt_util.UTC) - PENDING_RETENTION
        for slots in self._pending_energy.values():
            for timestamp in list(slots):
                if dt_util.parse_datetime(timestamp) < cutoff:
                    del slots[timestamp]

    # ---- demand estimate -------------------------------------------------------------------

    @property
    def _estimating(self) -> bool:
        return any(p.demand_estimate and p.demand_rate > 0 for p in self.timeline.plans)

    def _signature(self) -> str:
        """Identifies the settings the saved peaks were measured with; a change discards them."""
        return "|".join(
            f"{p.effective_from}:{p.demand_window_start}-{p.demand_window_end}/{p.demand_block_minutes}"
            for p in self.timeline.plans
            if p.demand_estimate
        )

    def _daily_charge(self, day: date) -> float:
        return self.timeline.plan_on(day).charge_per_day(
            day, self.ledger.demand_estimates()
        )

    async def _async_scan_demand(self, days: int, *, reprice: bool) -> None:
        """Serialize scans so an old request cannot overwrite state after unload."""
        async with self._demand_lock:
            if not self._stopping:
                await self._async_scan_demand_locked(days, reprice=reprice)

    async def _async_scan_demand_locked(self, days: int, *, reprice: bool) -> None:
        """Read recent 5-minute import statistics, find each month's highest block, merge it in."""
        now = dt_util.now()
        recorder = get_instance(self.hass)
        entity = self.import_entity

        def fetch() -> list[dict[str, Any]]:
            result = _statistics_result(
                statistics_during_period(
                    self.hass,
                    (now - timedelta(days=days)).astimezone(dt_util.UTC),
                    now.astimezone(dt_util.UTC),
                    {entity},
                    "5minute",
                    {"energy": "Wh"},
                    {"change"},
                )
            )
            return result.get(entity, [])

        rows = await recorder.async_add_executor_job(fetch)
        if self._stopping:
            return
        per_plan: dict[date, list[tuple[datetime, float]]] = {}
        discarded = 0
        for row in rows:
            try:
                change = float(row["change"])
                when = dt_util.as_local(_row_start(row))
            except (KeyError, TypeError, ValueError, OverflowError, OSError):
                discarded += 1
                continue
            if (
                not math.isfinite(change)
                or change < 0
                or change / 1000.0 > MAX_SLOT_KWH
                or when > now
            ):
                discarded += 1
                continue
            plan = self.timeline.plan_on(when.date())
            if plan.demand_estimate and plan.demand_rate > 0:
                per_plan.setdefault(plan.effective_from, []).append(
                    (when, change / 1000.0)
                )
        if discarded:
            _LOGGER.debug("Filtered %d invalid or out-of-range demand rows", discarded)
        changed: set[str] = set()
        for plan in self.timeline.plans:
            slots = per_plan.get(plan.effective_from)
            if not slots:
                continue
            found = block_peaks(
                slots,
                start_hour=plan.demand_window_start,
                end_hour=plan.demand_window_end,
                block_minutes=plan.demand_block_minutes,
            )
            changed |= self.ledger.merge_demand_peaks(found)
        if changed and reprice:
            self.ledger.reprice_fixed_days(changed, self._daily_charge)
            self._store.async_delay_save(self._snapshot, SAVE_DELAY_SECONDS)
            async_dispatcher_send(self.hass, signal_update(self.entry_id))

    async def _on_demand_tick(self, _now: Any) -> None:
        try:
            await self._async_scan_demand(1, reprice=True)
        except Exception as err:  # noqa: BLE001 - a failed scan must not stop the timer
            _LOGGER.warning(
                "Could not refresh the demand estimate (%s); retrying at the next interval",
                type(err).__name__,
            )

    def _load_solar_progress(self, stored: dict[str, Any], now: datetime) -> None:
        """Where live solar pricing stopped, and which hours had no import reading."""
        through = dt_util.parse_datetime(str(stored.get("solar_settled_through", "")))
        if through is not None and through.tzinfo is not None and through <= now:
            self._saved_settled_through = through.astimezone(dt_util.UTC)
        forced = stored.get("solar_forced", [0.0, 0.0])
        if (
            isinstance(forced, list)
            and len(forced) == 2
            and all(
                isinstance(v, (int, float)) and math.isfinite(v) and v >= 0
                for v in forced
            )
        ):
            self._forced = [float(forced[0]), float(forced[1])]
        gaps = stored.get("import_gaps", {})
        if isinstance(gaps, dict):
            self._import_gaps = {
                str(hour): bool(still_offline)
                for hour, still_offline in gaps.items()
                if dt_util.parse_datetime(str(hour))
            }

    def _snapshot(self) -> dict:
        data = self.ledger.to_dict()
        if self._settled_through is not None:
            data["solar_settled_through"] = self._settled_through.isoformat()
        if self._import_gaps:
            data["import_gaps"] = dict(self._import_gaps)
        if any(self._forced):
            data["solar_forced"] = list(self._forced)
        data["demand_signature"] = self._signature()
        data["history_start"] = self._history_start.isoformat()
        data["pending_energy"] = {
            source: dict(slots) for source, slots in self._pending_energy.items()
        }
        return data

    def demand_status(self) -> dict[str, Any] | None:
        """This month's demand: billed kW if known, else the estimate. None if no demand charge."""
        today = dt_util.now().date()
        plan = self.timeline.plan_on(today)
        if plan.demand_rate <= 0:
            return None
        month = today.strftime("%Y-%m")
        billed = plan.demand_kw.get(month)
        peak = self.ledger.demand_peaks.get(month) if plan.demand_estimate else None
        if billed is not None:
            kw, source = billed, "billed"
        elif peak is not None:
            kw, source = float(peak["kw"]), "estimated"
        else:
            kw, source = None, "none"
        return {
            "kw": kw,
            "source": source,
            "estimated_kw": float(peak["kw"]) if peak else None,
            "peak_at": peak["at"] if peak else None,
            "billed_kw": billed,
            "window": f"{plan.demand_window_start:02d}:00-{plan.demand_window_end % 24:02d}:00",
            "block_minutes": plan.demand_block_minutes,
        }

    async def async_stop(self) -> None:
        """Unsubscribe, wait for in-flight demand reads and flush persisted data."""
        self.async_unsubscribe()
        async with self._demand_lock:
            await self._store.async_save(self._snapshot())

    @callback
    def async_unsubscribe(self) -> None:
        """Stop event/timer subscriptions without writing an incomplete startup ledger."""
        self._stopping = True
        for unsub in self._unsubs:
            unsub()
        self._unsubs.clear()

    def _ensure_today(self, today: date) -> None:
        self.ledger.ensure_fixed_through(today, self._daily_charge)

    @callback
    def _on_source_change(self, event: Event) -> None:
        if self._stopping:
            return
        entity = event.data["entity_id"]
        state = event.data.get("new_state")
        value = energy_value(state)
        watched = self._watched()
        if self.solar_mode and entity == self.import_entity:
            self._note_import(dt_util.now(), online=value is not None)
        if value is None or entity not in watched:
            async_dispatcher_send(self.hass, signal_update(self.entry_id))
            return
        key, pricer = watched[entity]
        now = dt_util.now()
        self._ensure_today(now.date())
        old_state = event.data.get("old_state")
        last_reset = state.attributes.get("last_reset")
        reset = state.attributes.get("state_class") == "total_increasing" or (
            last_reset is not None
            and old_state is not None
            and old_state.attributes.get("last_reset") != last_reset
        )
        plan = self.timeline.plan_on(now.date())
        if pricer is None or (self.solar_mode and key in self._device_keys):
            # Solar is only an input; devices are priced per slot by `_settle`.
            delta = self.ledger.reading_delta(key, value, reset_on_decrease=reset)
        elif key == "export" and plan.export_daily_cap:
            delta = self.ledger.reading_delta(key, value, reset_on_decrease=reset)
            book_export_day(self.ledger, key, now.date(), delta, plan)
        else:
            delta = self.ledger.record(key, value, now, pricer, reset_on_decrease=reset)
        self._remember_increment(key, now, delta)
        self._store.async_delay_save(self._snapshot, SAVE_DELAY_SECONDS)
        async_dispatcher_send(self.hass, signal_update(self.entry_id))

    @callback
    def _on_tick(self, _now: Any) -> None:
        if self._stopping:
            return
        now = dt_util.now()
        today = now.date()
        self._ensure_today(today)
        if (
            self.solar_mode
            and energy_value(self.hass.states.get(self.import_entity)) is None
        ):
            self._note_import(now, online=False)
        self._settle(now)
        self.ledger.prune(today)
        self._prune_pending(now)
        self._store.async_delay_save(self._snapshot, SAVE_DELAY_SECONDS)
        async_dispatcher_send(self.hass, signal_update(self.entry_id))

    def summary(self) -> dict[str, float]:
        return summarize(self.ledger, dt_util.now().date())

    def source_available(self, source: str) -> bool:
        """Whether the meter behind a cost/usage sensor currently has valid data."""
        if source in self._sources:
            return energy_value(self.hass.states.get(source)) is not None
        return any(
            key == source and energy_value(self.hass.states.get(entity)) is not None
            for entity, (key, _pricer) in self._sources.items()
        )

