    def _new_point(self, key: str, km: float, at: datetime) -> dict[str, Any]:
        """A window starting now, from this reading."""
        local = dt_util.as_local(at)
        return {
            "start_day": local.date().isoformat(),
            "start_at": at.astimezone(dt_util.UTC).isoformat(),
            "start_km": km,
            "month": local.strftime("%Y-%m"),
            "month_km": km,
            "last_km": km,
            "last_at": at.astimezone(dt_util.UTC).isoformat(),
            "source": self._distance_identity[key],
        }

    def _mirror(self, key: str) -> None:
        """Copy the charger's bookings from the window's start into its distance source."""
        point = self.distance.points[key]
        start = dt_util.parse_datetime(
            point.get("start_at", "")
        ) or dt_util.start_of_local_day(date.fromisoformat(point["start_day"]))
        self.ledger.mirrors[key] = (distance_key(key), start)

    async def _async_distance_history(self, now: datetime) -> None:
        """Start each window where both the odometer and the charger have recorder data.

        The odometer's daily statistics give each day's closing reading. The window starts
        on the first day both have data, from the odometer's reading at the close of the
        day before, so the kilometres and the charger's cost cover the same days.
        """
        odometers = {
            roles["odometer"]: key for key, roles in self._distance_links.items()
        }
        chargers = {
            entity: key
            for entity, (key, _pricer) in self._sources.items()
            if key in self._distance_links
        }
        today = now.date()

        def fetch() -> dict[str, list[dict[str, Any]]]:
            return _statistics_result(
                statistics_during_period(
                    self.hass,
                    HISTORY_EPOCH,
                    now.astimezone(dt_util.UTC),
                    set(odometers) | set(chargers),
                    "day",
                    {"distance": "km", "energy": "Wh"},
                    {"state", "change"},
                )
            )

        try:
            daily = await get_instance(self.hass).async_add_executor_job(fetch)
        except (OSError, HomeAssistantError, SQLAlchemyError, ValueError) as err:
            _LOGGER.warning(
                "Could not read odometer history (%s); using saved readings",
                type(err).__name__,
            )
            return
        first_charged = {
            key: min(
                (
                    dt_util.as_local(_row_start(row)).date()
                    for row in daily.get(entity, [])
                ),
                default=None,
            )
            for entity, key in chargers.items()
        }
        month_start = date(today.year, today.month, 1)
        for odometer, key in odometers.items():
            if self._distance_identity[key] in self._distance_reset:
                continue
            closing: list[tuple[date, float]] = []  # complete days only
            for row in daily.get(odometer, []):
                try:
                    day = dt_util.as_local(_row_start(row)).date()
                    km = float(row["state"])
                except (KeyError, TypeError, ValueError, OverflowError, OSError):
                    continue
                if day < today and math.isfinite(km) and km >= 0:
                    closing.append((day, km))
            charged = first_charged.get(key)
            if not closing or charged is None:
                continue
            closing.sort()
            start_day = max(closing[0][0] + timedelta(days=1), charged)
            before = [km for day, km in closing if day < start_day]
            if start_day > today or not before:
                continue
            point = {
                "start_day": start_day.isoformat(),
                "start_km": before[-1],
                "source": self._distance_identity[key],
                "month": month_start.strftime("%Y-%m"),
                "month_km": before[-1],
            }
            if month_start > start_day:
                in_month = [km for day, km in closing if day < month_start]
                point["month_km"] = in_month[-1]
            if saved := self.distance.points.get(key):
                for field in ("last_km", "last_at"):
                    if field in saved:
                        point[field] = saved[field]
            self.distance.points[key] = point

    async def _async_backfill_charges(self, now: datetime) -> None:
        """On a new link, find the last week's charging at home and away."""
        new = {
            key: roles
            for key, roles in self._distance_links.items()
            if {"battery", "location"} <= set(roles)
            and key not in self.distance.charges
            and key not in self.distance.last_level
        }
        if not new:
            return
        now_utc = now.astimezone(dt_util.UTC)
        entities = sorted(
            {roles[r] for roles in new.values() for r in ("battery", "location")}
        )

        def fetch() -> dict[str, list[Any]]:
            return get_significant_states(
                self.hass,
                now_utc - MODE_BACKFILL,
                now_utc,
                entities,
                significant_changes_only=False,
                no_attributes=False,  # The battery level's unit is checked.
            )

        try:
            states = await get_instance(self.hass).async_add_executor_job(fetch)
        except (OSError, HomeAssistantError, SQLAlchemyError, ValueError) as err:
            _LOGGER.warning(
                "Could not read battery history (%s); charging is tracked from now on",
                type(err).__name__,
            )
            return
        for key, roles in new.items():
            events = sorted(
                (
                    (state.last_changed, role, state)
                    for role in ("location", "battery")  # Where, then what, on a tie.
                    for state in states.get(roles[role], [])
                    if isinstance(state, State)
                ),
                key=lambda event: (event[0], event[1] == "battery"),
            )
            location: State | None = None
            for changed, role, state in events:
                if role == "location":
                    location = state
                elif (level := battery_level(state)) is not None:
                    self.distance.note_charge(
                        key, level, at_home(location), dt_util.as_local(changed).date()
                    )

    def _start_distance(self, now: datetime) -> None:
        """Start a link without history from the current reading, and copy charger costs."""
        # A month that turned while HA was off starts from the last reading before.
        self._roll_distance_month(now)
        for key, roles in self._distance_links.items():
            km = odometer_km(self.hass.states.get(roles["odometer"]))
            point = self.distance.points.get(key)
            if point is None:
                if km is None:
                    continue  # Started on the first reading.
                point = self.distance.points[key] = self._new_point(key, km, now)
            elif km is not None:
                self._accept_km(point, km, now)
            self._mirror(key)
            if (level := battery_level(self._state(roles, "battery"))) is not None and (
                key not in self.distance.last_level
            ):
                self.distance.last_level[key] = level

    @staticmethod
    def _accept_km(point: dict[str, Any], km: float, now: datetime) -> bool:
        """Take an odometer reading, unless it is a glitch."""
        return accept_km(point, km, now.astimezone(dt_util.UTC))

    def _state(self, roles: dict[str, str], role: str) -> State | None:
        return self.hass.states.get(roles[role]) if role in roles else None

    @callback
    def _on_distance_change(self, event: Event) -> None:
        if self._stopping:
            return
        entity_id = event.data["entity_id"]
        now = dt_util.now()
        changed = False
        for key, roles in self._distance_links.items():
            if roles.get("odometer") == entity_id:
                km = odometer_km(event.data.get("new_state"))
                if km is not None:
                    if key not in self.distance.points:
                        self.distance.points[key] = self._new_point(key, km, now)
                        self._mirror(key)
                        changed = True
                    else:
                        changed |= self._accept_km(self.distance.points[key], km, now)
            if roles.get("battery") == entity_id:
                level = battery_level(event.data.get("new_state"))
                if level is not None:
                    home = at_home(self._state(roles, "location"))
                    changed |= self.distance.note_charge(key, level, home, now.date())
        if changed:
            self._request_save()
            async_dispatcher_send(self.hass, signal_update(self.entry_id))

    def _roll_distance_month(self, now: datetime) -> None:
        """At the start of a month, the last reading becomes the month's start."""
        month = dt_util.as_local(now).strftime("%Y-%m")
        for point in self.distance.points.values():
            if point.get("month") != month and "last_km" in point:
                point["month"] = month
                point["month_km"] = point["last_km"]

    def distance_links(self) -> dict[str, tuple[str, dict[str, str]]]:
        """Tracked charger entity -> (its ledger key, its linked entities)."""
        return {
            entity: (key, self._distance_links[key])
            for entity, (key, _p) in self._sources.items()
            if key in self._distance_links
        }

    def distance_values(self, key: str) -> dict[str, Any]:
        """Distance, and cost and energy per 100 km, for the month and since the start."""
        point = self.distance.points.get(key)
        if point is None or "last_km" not in point:
            return {}
        today = dt_util.now().date()
        start_day = date.fromisoformat(point["start_day"])
        month_start = max(date(today.year, today.month, 1), start_day)
        km_month = max(point["last_km"] - point.get("month_km", point["start_km"]), 0.0)
        km_total = max(point["last_km"] - point["start_km"], 0.0)
        source = distance_key(key)
        _cost_today, cost_month = device_cost(self.ledger, source, today)
        kwh_month = sum(band_kwh(self.ledger, source, today, "month").values())
        total = self.ledger.totals.get(source, {"kwh": 0.0, "cost": 0.0})

        def per_100(amount: float, km: float, digits: int) -> float | None:
            return round(amount / km * 100, digits) if km >= 1 else None

        def away_share(since: date) -> float | None:
            home, away = self.distance.charge_split(key, since)
            return round(away / (home + away) * 100, 1) if home + away > 0 else None

        return {
            "km_month": round(km_month, 1),
            "km_total": round(km_total, 1),
            "cost_100_month": per_100(cost_month, km_month, 2),
            "cost_100_total": per_100(total["cost"], km_total, 2),
            "kwh_100_month": per_100(kwh_month, km_month, 1),
            "kwh_100_total": per_100(total["kwh"], km_total, 1),
            "away_month": away_share(month_start),
            "away_total": away_share(start_day),
            "since": point["start_day"],
        }

    def mode_since(self, key: str) -> str | None:
        return self.modes.since(key)

    @property
    def device_pricing(self) -> str:
        """How tracked devices are priced: at the grid share, or at the full import rate."""
        return "solar_share" if self.solar_mode else "import_rate"

    def _remember_increment(self, source: str, when: datetime, amount: float) -> None:
        """Aggregate live increments into five-minute buckets, bounded to one day."""
        if amount <= 0:
            return
        at = when.astimezone(dt_util.UTC)
        slot = at.replace(
            minute=at.minute // 5 * 5, second=0, microsecond=0
        ).isoformat()
        slots = self._pending_energy.setdefault(source, {})
        slots[slot] = slots.get(slot, 0.0) + amount
        self._prune_pending(when)

    def _prune_pending(self, now: datetime) -> None:
        cutoff = now.astimezone(dt_util.UTC) - PENDING_RETENTION
        for slots in self._pending_energy.values():
            for timestamp in list(slots):
                if dt_util.parse_datetime(timestamp) < cutoff:
                    del slots[timestamp]

    # ---- demand estimate -------------------------------------------------------------------

    @property
    def _estimating(self) -> bool:
        return any(p.demand_estimate and p.demand_rate > 0 for p in self.timeline.plans)

    def _signature(self) -> str:
        """Identifies the settings the saved peaks were measured with; a change discards them."""
        return "|".join(
            f"{p.effective_from}:{p.demand_window_start}-{p.demand_window_end}/{p.demand_block_minutes}"
            for p in self.timeline.plans
            if p.demand_estimate
        )

    def _daily_charge(self, day: date) -> float:
        return self.timeline.plan_on(day).charge_per_day(
            day, self.ledger.demand_estimates()
        )

    async def _async_scan_demand(self, days: int, *, reprice: bool) -> None:
        """Serialize scans so an old request cannot overwrite state after unload."""
        async with self._demand_lock:
            if not self._stopping:
                await self._async_scan_demand_locked(days, reprice=reprice)

    async def _async_scan_demand_locked(self, days: int, *, reprice: bool) -> None:
        """Read recent 5-minute import statistics, find each month's highest block, merge it in."""
        now = dt_util.now()
        recorder = get_instance(self.hass)
        entity = self.import_entity

        def fetch() -> list[dict[str, Any]]:
            result = _statistics_result(
                statistics_during_period(
                    self.hass,
                    (now - timedelta(days=days)).astimezone(dt_util.UTC),
                    now.astimezone(dt_util.UTC),
                    {entity},
                    "5minute",
                    {"energy": "Wh"},
                    {"change"},
                )
            )
            return result.get(entity, [])

        rows = await recorder.async_add_executor_job(fetch)
        if self._stopping:
            return
        per_plan: dict[date, list[tuple[datetime, float]]] = {}
        discarded = 0
        for row in rows:
            try:
                change = float(row["change"])
                when = dt_util.as_local(_row_start(row))
            except (KeyError, TypeError, ValueError, OverflowError, OSError):
                discarded += 1
                continue
            if (
                not math.isfinite(change)
                or change < 0
                or change / 1000.0 > MAX_SLOT_KWH
                or when > now
            ):
                discarded += 1
                continue
            plan = self.timeline.plan_on(when.date())
            if plan.demand_estimate and plan.demand_rate > 0:
                per_plan.setdefault(plan.effective_from, []).append(
                    (when, change / 1000.0)
                )
        if discarded:
            _LOGGER.debug("Filtered %d invalid or out-of-range demand rows", discarded)
        changed: set[str] = set()
        for plan in self.timeline.plans:
            slots = per_plan.get(plan.effective_from)
            if not slots:
                continue
            found = block_peaks(
                slots,
                start_hour=plan.demand_window_start,
                end_hour=plan.demand_window_end,
                block_minutes=plan.demand_block_minutes,
            )
            changed |= self.ledger.merge_demand_peaks(found)
        if changed and reprice:
            self.ledger.reprice_fixed_days(changed, self._daily_charge)
            self._request_save()
            async_dispatcher_send(self.hass, signal_update(self.entry_id))

    async def _on_demand_tick(self, _now: Any) -> None:
        try:
            await self._async_scan_demand(1, reprice=True)
        except Exception as err:  # noqa: BLE001 - a failed scan must not stop the timer
            _LOGGER.warning(
                "Could not refresh the demand estimate (%s); retrying at the next interval",
                type(err).__name__,
            )

    def _load_solar_progress(self, stored: dict[str, Any], now: datetime) -> None:
        """Where live solar pricing stopped, and which hours had no import reading."""
        through = dt_util.parse_datetime(str(stored.get("solar_settled_through", "")))
        if through is not None and through.tzinfo is not None and through <= now:
            self._saved_settled_through = through.astimezone(dt_util.UTC)
        forced = stored.get("solar_forced", [0.0, 0.0])
        if (
            isinstance(forced, list)
            and len(forced) == 2
            and all(
                isinstance(v, (int, float)) and math.isfinite(v) and v >= 0
                for v in forced
            )
        ):
            self._forced = [float(forced[0]), float(forced[1])]
        gaps = stored.get("import_gaps", {})
        if isinstance(gaps, dict):
            self._import_gaps = {
                str(hour): bool(still_offline)
                for hour, still_offline in gaps.items()
                if dt_util.parse_datetime(str(hour))
            }

    def _request_save(self) -> None:
        """Save soon. A save already on its way is not pushed back by newer readings,
        so a meter that never pauses can't keep the data in memory forever."""
        if not self._save_pending:
            self._save_pending = True
            self._store.async_delay_save(self._snapshot_for_save, SAVE_DELAY_SECONDS)

    def _snapshot_for_save(self) -> dict:
        self._save_pending = False
        return self._snapshot()

    def _snapshot(self) -> dict:
        data = self.ledger.to_dict()
        if self._settled_through is not None:
            data["solar_settled_through"] = self._settled_through.isoformat()
        if self._import_gaps:
            data["import_gaps"] = dict(self._import_gaps)
        if any(self._forced):
            data["solar_forced"] = list(self._forced)
        if self._distance_links:
            data["distance"] = self.distance.to_dict()
        if self._mode_links:
            self.modes.last.update(self._current_mode)
            data["modes"] = self.modes.to_dict()
        data["demand_signature"] = self._signature()
        data["history_start"] = self._history_start.isoformat()
        data["pending_energy"] = {
            source: dict(slots) for source, slots in self._pending_energy.items()
        }
        return data

    def demand_status(self) -> dict[str, Any] | None:
        """This month's demand: billed kW if known, else the estimate. None if no demand charge."""
        today = dt_util.now().date()
        plan = self.timeline.plan_on(today)
        if plan.demand_rate <= 0:
            return None
        month = today.strftime("%Y-%m")
        billed = plan.demand_kw.get(month)
        peak = self.ledger.demand_peaks.get(month) if plan.demand_estimate else None
        if billed is not None:
            kw, source = billed, "billed"
        elif peak is not None:
            kw, source = float(peak["kw"]), "estimated"
        else:
            kw, source = None, "none"
        return {
            "kw": kw,
            "source": source,
            "estimated_kw": float(peak["kw"]) if peak else None,
            "peak_at": peak["at"] if peak else None,
            "billed_kw": billed,
            "window": f"{plan.demand_window_start:02d}:00-{plan.demand_window_end % 24:02d}:00",
            "block_minutes": plan.demand_block_minutes,
        }

    async def async_stop(self) -> None:
        """Unsubscribe, wait for in-flight demand reads and flush persisted data."""
        self.async_unsubscribe()
        async with self._demand_lock:
            self._save_pending = False
            await self._store.async_save(self._snapshot())

    @callback
    def async_unsubscribe(self) -> None:
        """Stop event/timer subscriptions without writing an incomplete startup ledger."""
        self._stopping = True
        for unsub in self._unsubs:
            unsub()
        self._unsubs.clear()

    def _ensure_today(self, today: date) -> None:
        self.ledger.ensure_fixed_through(today, self._daily_charge)

    @callback
    def _on_source_change(self, event: Event) -> None:
        if self._stopping:
            return
        entity = event.data["entity_id"]
        state = event.data.get("new_state")
        value = energy_value(state)
        watched = self._watched()
        if self.solar_mode and entity == self.import_entity:
            self._note_import(dt_util.now(), online=value is not None)
        if value is None or entity not in watched:
            async_dispatcher_send(self.hass, signal_update(self.entry_id))
            return
        key, pricer = watched[entity]
        now = dt_util.now()
        self._ensure_today(now.date())
        old_state = event.data.get("old_state")
        last_reset = state.attributes.get("last_reset")
        reset = state.attributes.get("state_class") == "total_increasing" or (
            last_reset is not None
            and old_state is not None
            and old_state.attributes.get("last_reset") != last_reset
        )
        plan = self.timeline.plan_on(now.date())
        if pricer is None or (self.solar_mode and key in self._device_keys):
            # Solar is only an input; devices are priced per slot by `_settle`.
            delta = self.ledger.reading_delta(key, value, reset_on_decrease=reset)
        elif key == "export" and plan.export_daily_cap:
            delta = self.ledger.reading_delta(key, value, reset_on_decrease=reset)
            book_export_day(self.ledger, key, now.date(), delta, plan)
        else:
            delta = self.ledger.record(key, value, now, pricer, reset_on_decrease=reset)
        self._remember_increment(key, now, delta)
        if key in self._mode_links and delta > 0:
            mode = self._current_mode.get(key, UNKNOWN_MODE)
            slot = _slot(now)
            self.modes.add(key, slot, mode, delta)
            if self.modes.note_names(key, [mode]):
                async_dispatcher_send(self.hass, signal_modes(self.entry_id))
            if not self.solar_mode and pricer is not None:
                band, price = pricer(now)  # Priced now, like the device itself.
                self._book_modes(key, now, band, delta, price, {mode: 1.0})
        self._request_save()
        async_dispatcher_send(self.hass, signal_update(self.entry_id))

    @callback
    def _on_tick(self, _now: Any) -> None:
        if self._stopping:
            return
        now = dt_util.now()
        today = now.date()
        self._ensure_today(today)
        if (
            self.solar_mode
            and energy_value(self.hass.states.get(self.import_entity)) is None
        ):
            self._note_import(now, online=False)
        self._settle(now)
        self._settle_modes(now)
        self._roll_distance_month(now)
        self.ledger.prune(today)
        self._prune_pending(now)
        self._request_save()
        async_dispatcher_send(self.hass, signal_update(self.entry_id))

    def summary(self) -> dict[str, float]:
        return summarize(self.ledger, dt_util.now().date())

    def source_available(self, source: str) -> bool:
        """Whether the meter behind a cost/usage sensor currently has valid data."""
        if source in self._sources:
            return energy_value(self.hass.states.get(source)) is not None
        return any(
            key == source and energy_value(self.hass.states.get(entity)) is not None
            for entity, (key, _pricer) in self._sources.items()
        )

    def band_kwh(self, source: str, scope: str) -> dict[str, float]:
        return band_kwh(self.ledger, source, dt_util.now().date(), scope)

    def current(self) -> tuple[Band, float, int]:
        return current_tariff(self.timeline, dt_util.now())

    def device_costs(self, entity: str) -> tuple[float, float]:
        ledger_key = self._sources.get(entity, (entity, self._import_price))[0]
        return device_cost(self.ledger, ledger_key, dt_util.now().date())

    def device_sensor_key(self, entity: str) -> str:
        """Return the persistent sensor identity independently of its meter's name."""
        return self._device_sensor_keys.get(
            entity, f"device_{entity.split('.', 1)[-1]}"
        )

    def lifetime_import(self) -> float:
        return round(
            self.ledger.lifetime_cost("import") + self.ledger.lifetime_cost(FIXED_KEY),
            2,
        )

    def lifetime_export(self) -> float:
        return round(self.ledger.lifetime_cost("export"), 2)

    def lifetime_device(self, entity: str) -> float:
        ledger_key = self._sources.get(entity, (entity, self._import_price))[0]
        return round(self.ledger.lifetime_cost(ledger_key), 2)
