def _current_attrs(rt: TariffRuntime) -> dict[str, Any]:
    _band, rate, until = rt.current()
    return {"rate_inc_gst": round(rate, 4), "next_change": f"{until:02d}:00"}


def _pricing_attrs(rt: TariffRuntime) -> dict[str, Any]:
    return {"pricing": rt.device_pricing}


def _money(
    key: str,
    name: str,
    fn: Callable[[TariffRuntime], Any],
    *,
    source: str = "import",
    attrs_fn: Callable[[TariffRuntime], dict[str, Any]] | None = None,
) -> TariffSensorDescription:
    """Cost for today or the month to date. It resets each period, so it has no
    state class: that keeps it out of the Energy dashboard's cost picker, which
    needs a value that only rises (use the lifetime "total" sensors there)."""
    return TariffSensorDescription(
        key=key,
        name=name,
        native_unit_of_measurement="AUD",
        device_class=SensorDeviceClass.MONETARY,
        suggested_display_precision=2,
        value_fn=fn,
        source=source,
        attrs_fn=attrs_fn,
    )


def _lifetime(
    key: str,
    name: str,
    fn: Callable[[TariffRuntime], Any],
    *,
    source: str = "import",
    object_name: str | None = None,
    attrs_fn: Callable[[TariffRuntime], dict[str, Any]] | None = None,
) -> TariffSensorDescription:
    """Cumulative cost, for the Energy dashboard. Only ever rises, so state class is total."""
    return TariffSensorDescription(
        key=key,
        name=name,
        native_unit_of_measurement="AUD",
        device_class=SensorDeviceClass.MONETARY,
        state_class=SensorStateClass.TOTAL,  # monetary only accepts total (not total_increasing)
        suggested_display_precision=2,
        value_fn=fn,
        source=source,
        object_name=object_name,
        attrs_fn=attrs_fn,
    )


def _kwh(
    key: str,
    name: str,
    fn: Callable[[TariffRuntime], Any],
    *,
    source: str,
    lifetime: bool = False,
) -> TariffSensorDescription:
    """kWh for today or the month to date, which reset each period like a utility meter.

    A lifetime value is rebuilt from history on every start and may be corrected
    downwards, so it is a plain total: a fall must not be read as a meter reset.
    """
    return TariffSensorDescription(
        key=key,
        name=name,
        native_unit_of_measurement="kWh",
        device_class=SensorDeviceClass.ENERGY,
        state_class=(
            SensorStateClass.TOTAL if lifetime else SensorStateClass.TOTAL_INCREASING
        ),
        suggested_display_precision=2,
        value_fn=fn,
        source=source,
    )


def _device_label(hass: HomeAssistant, entity_id: str) -> str | None:
    """The meter's default name: its device's name plus the sensor's own name.

    A rename of the meter entity (for example "Total Energy Consumed") would otherwise
    replace the device name in every cost sensor built from it. A name given to the
    device is kept. Meters without a device keep their display name.
    """
    entry = er.async_get(hass).async_get(entity_id)
    if entry is None or entry.device_id is None or not entry.has_entity_name:
        return None
    device = dr.async_get(hass).async_get(entry.device_id)
    device_name = device and (device.name_by_user or device.name)
    if not device_name:
        return None
    return (
        f"{device_name} {entry.original_name}" if entry.original_name else device_name
    )


def _mode_descriptions(rt: TariffRuntime) -> list[TariffSensorDescription]:
    """Cost and energy per mode for every tracked meter linked to a mode entity."""
    out: list[TariffSensorDescription] = []
    for device, (key, _mode_entity) in rt.mode_links().items():
        base = _device_label(rt.hass, device)
        if base is None:
            state = rt.hass.states.get(device)
            base = (state and state.attributes.get("friendly_name")) or (
                device.split(".", 1)[-1].replace("_", " ").capitalize()
            )
        sensor_key = rt.device_sensor_key(device)

        def attrs(r: TariffRuntime, k: str = key) -> dict[str, Any]:
            return {"pricing": r.device_pricing, "since": r.mode_since(k)}

        modes = rt.mode_names(key)
        pretty_names = pretty_modes(modes)
        for mode in modes:
            pretty = pretty_names[mode]
            stem = f"{sensor_key}_mode_{mode_slug(mode)}"
            for scope, label in (("today", "today"), ("month", "month to date")):
                out.append(
                    _money(
                        f"{stem}_cost_{scope}",
                        f"{base} {pretty} cost {label}",
                        lambda r, k=key, m=mode, s=scope: r.mode_values(k, m)[
                            f"cost_{s}"
                        ],
                        source=device,
                        attrs_fn=attrs,
                    )
                )
                out.append(
                    _kwh(
                        f"{stem}_kwh_{scope}",
                        f"{base} {pretty} energy {label}",
                        lambda r, k=key, m=mode, s=scope: r.mode_values(k, m)[
                            f"kwh_{s}"
                        ],
                        source=device,
                    )
                )
            out.append(
                _lifetime(
                    f"{stem}_cost_total",
                    f"{base} {pretty} cost total",
                    lambda r, k=key, m=mode: r.mode_values(k, m)["cost_total"],
                    source=device,
                    attrs_fn=attrs,
                )
            )
            out.append(
                _kwh(
                    f"{stem}_kwh_total",
                    f"{base} {pretty} energy total",
                    lambda r, k=key, m=mode: r.mode_values(k, m)["kwh_total"],
                    source=device,
                    lifetime=True,
                )
            )
    return out


def _distance_descriptions(rt: TariffRuntime) -> list[TariffSensorDescription]:
    """Distance, and charging cost and energy per 100 km, for a charger with an odometer."""
    out: list[TariffSensorDescription] = []
    for device, (key, _roles) in rt.distance_links().items():
        base = _device_label(rt.hass, device)
        if base is None:
            state = rt.hass.states.get(device)
            base = (state and state.attributes.get("friendly_name")) or (
                device.split(".", 1)[-1].replace("_", " ").capitalize()
            )
        stem = rt.device_sensor_key(device)

        def value(field: str, k: str = key) -> Callable[[TariffRuntime], Any]:
            return lambda r: r.distance_values(k).get(field)

        def attrs(
            scope: str, k: str = key
        ) -> Callable[[TariffRuntime], dict[str, Any]]:
            def build(r: TariffRuntime) -> dict[str, Any]:
                values = r.distance_values(k)
                return {
                    "pricing": r.device_pricing,
                    "since": values.get("since"),
                    "away_charging_percent": values.get(f"away_{scope}"),
                }

            return build

        for scope, label in (("month", "month to date"), ("total", "total")):
            out += [
                TariffSensorDescription(
                    key=f"{stem}_distance_{scope}",
                    name=f"{base} distance {label}",
                    native_unit_of_measurement="km",
                    device_class=SensorDeviceClass.DISTANCE,
                    state_class=(
                        SensorStateClass.TOTAL_INCREASING
                        if scope == "month"
                        else SensorStateClass.TOTAL
                    ),
                    suggested_display_precision=0,
                    value_fn=value(f"km_{scope}"),
                    source=device,
                ),
                TariffSensorDescription(
                    key=f"{stem}_cost_per_100km_{scope}",
                    name=f"{base} charging cost per 100 km {label}",
                    native_unit_of_measurement="AUD/100 km",
                    state_class=SensorStateClass.MEASUREMENT,
                    suggested_display_precision=2,
                    icon="mdi:cash-marker",
                    value_fn=value(f"cost_100_{scope}"),
                    attrs_fn=attrs(scope),
                    source=device,
                ),
                TariffSensorDescription(
                    key=f"{stem}_energy_per_100km_{scope}",
                    name=f"{base} energy per 100 km {label}",
                    native_unit_of_measurement="kWh/100km",
                    device_class=SensorDeviceClass.ENERGY_DISTANCE,
                    state_class=SensorStateClass.MEASUREMENT,
                    suggested_display_precision=1,
                    value_fn=value(f"kwh_100_{scope}"),
                    attrs_fn=attrs(scope),
                    source=device,
                ),
            ]
    return out


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def _band_descriptions(rt: TariffRuntime) -> list[TariffSensorDescription]:
    """Keep band sensors across dated plans, including future plan transitions."""
    groups: dict[tuple[str, str], set[str]] = {}
    for plan in rt.timeline.plans:
        schedules = [("import", plan.import_schedule)]
        if rt.export_entity and plan.export_schedule is not None:
            schedules.append(("export", plan.export_schedule))
        for source, schedule in schedules:
            names = [band.name for band in schedule.bands]
            if source == "export" and plan.export_daily_cap:
                names = ["fit_step_1", "fit_step_2"]
            for name in names:
                groups.setdefault((source, _slug(name)), set()).add(name)
    out: list[TariffSensorDescription] = []
    for (source, slug), names in groups.items():
        pretty = sorted(names)[0].replace("_", " ")
        for scope, scope_label in (("today", "today"), ("month", "month to date")):
            out.append(
                _kwh(
                    f"{source}_kwh_{slug}_{scope}",
                    f"{source.capitalize()} {pretty} kWh {scope_label}",
                    lambda r, s=source, bs=tuple(names), sc=scope: round(
                        sum(
                            value
                            for band, value in r.band_kwh(s, sc).items()
                            if band in bs
                        ),
                        3,
                    ),
                    source=source,
                )
            )
    return out


