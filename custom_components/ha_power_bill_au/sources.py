"""Keep meter identity independent of user-editable entity IDs.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any, TypedDict
from uuid import uuid4

from homeassistant.core import HomeAssistant, callback
from homeassistant.helpers import entity_registry as er

from .const import (
    CONF_EXPORT_ENTITY,
    CONF_IMPORT_ENTITY,
    CONF_SOURCES,
    CONF_TRACKED_DEVICES,
)


class SourceRecord(TypedDict):
    """Persist identity and the original opaque keys used by an existing source."""

    entity_id: str
    registry_id: str | None
    sensor_key: str
    ledger_key: str
    active: bool


def source_record(data: Mapping[str, Any], entity_id: str) -> SourceRecord:
    """Get an already resolved source, retaining legacy behavior before migration."""
    for record in data.get(CONF_SOURCES, {}).values():
        if record["entity_id"] == entity_id and record.get("active", True):
            return record
    return SourceRecord(
        entity_id=entity_id,
        registry_id=None,
        sensor_key=f"device_{entity_id.split('.', 1)[-1]}",
        ledger_key=entity_id,
        active=True,
    )


@callback
def prepare_sources(
    hass: HomeAssistant,
    data: Mapping[str, Any],
    options: Mapping[str, Any],
    *,
    devices: list[str] | None = None,
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Resolve known sources and bind selections without changing existing keys.

    Explicit device selections refer to the current registry. Saved selections
    follow their stored registry IDs, including when an old entity ID is reused
    by another meter. Records remain after deselection to avoid recycling keys.
    """
    registry = er.async_get(hass)
    prepared_data = dict(data)
    prepared_options = dict(options)
    records: dict[str, SourceRecord] = {}
    aliases: dict[str, str] = {}
    saved = data.get(CONF_SOURCES, {})
    if not isinstance(saved, Mapping):
        raise ValueError("Invalid saved meter identities")
    for token, saved_record in saved.items():
        if (
            not isinstance(token, str)
            or not isinstance(saved_record, Mapping)
            or any(
                not isinstance(saved_record.get(key), str)
                for key in ("entity_id", "sensor_key", "ledger_key")
            )
            or not isinstance(saved_record.get("registry_id"), (str, type(None)))
        ):
            raise ValueError("Invalid saved meter identity")
        record = SourceRecord(**saved_record)
        record["active"] = False
        if record["registry_id"] and (
            registered := registry.async_get(record["registry_id"])
        ):
            if record["entity_id"] != registered.entity_id:
                aliases[record["entity_id"]] = registered.entity_id
                record["entity_id"] = registered.entity_id
        records[token] = record

    def bind(entity_id: str) -> None:
        registered = registry.async_get(entity_id)
        for record in records.values():
            if registered and record["registry_id"] == registered.id:
                record["active"] = True
                return
            if record["entity_id"] != entity_id:
                continue
            if record["registry_id"] is None:
                # A previously unregistered source acquired a permanent identity.
                if registered:
                    record["registry_id"] = registered.id
                record["active"] = True
                return
            if registered is None:
                # Keep the identity of a temporarily missing registered source.
                record["active"] = True
                return

        token = uuid4().hex
        sensor_key = f"device_{entity_id.split('.', 1)[-1]}"
        ledger_key = entity_id
        if any(record["sensor_key"] == sensor_key for record in records.values()):
            sensor_key = f"device_{token}"
        if any(record["ledger_key"] == ledger_key for record in records.values()):
            ledger_key = f"source_{token}"
        records[token] = SourceRecord(
            entity_id=entity_id,
            registry_id=registered.id if registered else None,
            sensor_key=sensor_key,
            ledger_key=ledger_key,
            active=True,
        )

    for key in (CONF_IMPORT_ENTITY, CONF_EXPORT_ENTITY):
        if entity_id := prepared_data.get(key):
            entity_id = aliases.get(entity_id, entity_id)
            prepared_data[key] = entity_id
            bind(entity_id)
    selected = (
        list(devices)
        if devices is not None
        else [
            aliases.get(entity_id, entity_id)
            for entity_id in options.get(
                CONF_TRACKED_DEVICES, data.get(CONF_TRACKED_DEVICES, [])
            )
        ]
    )
    for entity_id in selected:
        bind(entity_id)
    if (
        CONF_TRACKED_DEVICES in data
        or CONF_TRACKED_DEVICES in options
        or devices is not None
    ):
        prepared_options[CONF_TRACKED_DEVICES] = selected
        prepared_data.pop(CONF_TRACKED_DEVICES, None)
    prepared_data[CONF_SOURCES] = records
    return prepared_data, prepared_options


@callback
def meter_pair(
    hass: HomeAssistant, data: Mapping[str, Any], options: Mapping[str, Any]
) -> tuple[str, str | None]:
    """Identify the same import/export pair even after registry entity renames."""
    prepared, _ = prepare_sources(hass, data, options)

    def identity(entity_id: str) -> str:
        record = source_record(prepared, entity_id)
        if record["registry_id"]:
            return f"registry:{record['registry_id']}"
        return f"entity:{entity_id}"

    return (
        identity(prepared[CONF_IMPORT_ENTITY]),
        identity(entity_id)
        if (entity_id := prepared.get(CONF_EXPORT_ENTITY))
        else None,
    )
