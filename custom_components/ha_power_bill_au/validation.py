"""Validate cumulative energy inputs and normalize readings to kWh.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import math
from typing import TypeGuard

from homeassistant.core import State
from homeassistant.util.unit_conversion import EnergyConverter

ENERGY_UNITS = {"Wh", "kWh", "MWh"}


def valid_energy_sensor(state: State | None) -> TypeGuard[State]:
    """Require an energy sensor with a cumulative state class and supported unit."""
    return state is not None and (
        state.domain == "sensor"
        and state.attributes.get("device_class") == "energy"
        and state.attributes.get("state_class") in {"total", "total_increasing"}
        and state.attributes.get("unit_of_measurement") in ENERGY_UNITS
    )


def energy_value(state: State | None) -> float | None:
    """Return finite, nonnegative kWh, or None for unavailable/invalid inputs."""
    if not valid_energy_sensor(state):
        return None
    try:
        value = float(state.state)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(value) or value < 0:
        return None
    value = EnergyConverter.convert(
        value, state.attributes["unit_of_measurement"], "kWh"
    )
    return value if math.isfinite(value) else None
