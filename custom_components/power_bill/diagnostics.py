from __future__ import annotations

from typing import Any

from homeassistant.core import HomeAssistant

from . import TariffConfigEntry


async def async_get_config_entry_diagnostics(
    hass: HomeAssistant, entry: TariffConfigEntry
) -> dict[str, Any]:
    """Return bounded, non-identifying configuration and runtime information."""
    runtime = entry.runtime_data
    return {
        "config_entry": {
            "version": entry.version,
            "minor_version": entry.minor_version,
        },
        "configuration": {
            "plan_count": len(runtime.timeline.plans),
            "tracked_meter_count": len(runtime.device_entities),
            "export_enabled": runtime.export_entity is not None,
            "demand_estimation_enabled": any(
                plan.demand_estimate for plan in runtime.timeline.plans
            ),
        },
        "runtime": {
            "retained_source_count": len(runtime.ledger.days),
            "saved_demand_months": len(runtime.ledger.demand_peaks),
            "import_available": runtime.source_available("import"),
            "export_available": runtime.source_available("export")
            if runtime.export_entity
            else None,
        },
    }
