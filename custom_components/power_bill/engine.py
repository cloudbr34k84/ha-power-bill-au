"""Pure tariff and usage-cost logic. No Home Assistant imports, so it is unit-testable.

Usage is priced when it is recorded, so a rate change only affects usage recorded after it.
Lifetime totals are kept separately from the daily detail, which is pruned.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta

KEEP_DAYS = 45
GST_RATE = 0.10
FIXED_KEY = "fixed"


@dataclass(frozen=True, kw_only=True)
class Band:
    """A named daily time window and its rate per kWh, as printed on the bill."""

    name: str
    start: int  # hour 0-23, inclusive
    end: int  # hour 1-24, exclusive; end <= start wraps past midnight
    rate: float

    def hours(self) -> list[int]:
        stop = self.end if self.end > self.start else self.end + 24
        return [h % 24 for h in range(self.start, stop)]


def validate_bands(bands: Iterable[Band]) -> str | None:
    """Return an error key, or None when the bands cover every hour exactly once."""
    bands = list(bands)
    if not bands:
        return "no_bands"
    names = [b.name.strip() for b in bands]
    if any(not n for n in names) or len(set(names)) != len(names):
        return "duplicate_names"
    covered: set[int] = set()
    for band in bands:
        if not (0 <= band.start <= 23 and 1 <= band.end <= 24) or band.start == band.end:
            return "invalid_window"
        if band.rate < 0:
            return "negative_rate"
        for hour in band.hours():
            if hour in covered:
                return "overlap"
            covered.add(hour)
    if len(covered) != 24:
        return "gap"
    return None


class Schedule:
    """Maps each hour of the day to exactly one band."""

    def __init__(self, bands: Iterable[Band]) -> None:
        bands = tuple(bands)
        error = validate_bands(bands)
        if error:
            raise ValueError(error)
        self.bands = bands
        self._by_hour: list[Band] = [bands[0]] * 24
        for band in bands:
            for hour in band.hours():
                self._by_hour[hour] = band

    def band_at(self, hour: int) -> Band:
        return self._by_hour[hour % 24]

    def by_name(self, name: str) -> Band | None:
        return next((b for b in self.bands if b.name == name), None)

    def next_change(self, hour: int) -> int:
        """Hour (0-23) at which the band after the current one begins."""
        current = self.band_at(hour)
        for step in range(1, 25):
            candidate = (hour + step) % 24
            if self.band_at(candidate) != current:
                return candidate
        return hour


@dataclass(frozen=True, kw_only=True)
class Plan:
    """One tariff plan, in force from `effective_from` until the next plan starts."""

    effective_from: date
    import_schedule: Schedule
    export_schedule: Schedule | None = None
    daily_supply: float = 0.0
    daily_membership: float = 0.0
    rates_include_gst: bool = True
    gst_rate: float = GST_RATE
    export_daily_cap: float = 0.0  # kWh per day credited at the export band rate; 0 = no daily cap
    export_over_cap_rate: float = 0.0  # $/kWh for export above the daily cap (the step-2 feed-in rate)
    demand_rate: float = 0.0  # $ per kW per day, e.g. 0.185
    demand_kw: dict[str, float] = field(default_factory=dict)  # "YYYY-MM" -> billed kW
    demand_estimate: bool = False  # estimate kW from meter data for months with no billed figure
    demand_window_start: int = 16  # demand is only measured from this hour...
    demand_window_end: int = 21  # ...until this hour (exclusive, 1-24)
    demand_block_minutes: int = 30  # length of the averaging block the retailer uses

    @property
    def import_factor(self) -> float:
        """Multiplier applied to import rates so the result is GST-inclusive."""
        return 1.0 if self.rates_include_gst else 1.0 + self.gst_rate

    @property
    def fixed_per_day(self) -> float:
        return (self.daily_supply + self.daily_membership) * self.import_factor

    def demand_kw_for(self, month: str, estimates: dict[str, float] | None = None) -> float:
        """kW charged for a month: the billed figure if there is one, else the estimate (if enabled)."""
        billed = self.demand_kw.get(month)
        if billed is not None:
            return billed
        if self.demand_estimate and estimates:
            return estimates.get(month, 0.0)
        return 0.0

    def demand_per_day(self, day: date, estimates: dict[str, float] | None = None) -> float:
        """Demand charge per day for that month's kW (0 when the month has none)."""
        kw = self.demand_kw_for(day.strftime("%Y-%m"), estimates)
        return kw * self.demand_rate * self.import_factor

    def charge_per_day(self, day: date, estimates: dict[str, float] | None = None) -> float:
        """Everything booked once per day: supply, membership and demand."""
        return self.fixed_per_day + self.demand_per_day(day, estimates)


class Timeline:
    """Plans ordered by start date. Each day (and each reading) is priced by the plan in force."""

    def __init__(self, plans: Iterable[Plan]) -> None:
        self.plans: tuple[Plan, ...] = tuple(sorted(plans, key=lambda p: p.effective_from))
        if not self.plans:
            raise ValueError("no_plans")
        starts = [p.effective_from for p in self.plans]
        if len(set(starts)) != len(starts):
            raise ValueError("duplicate_start")

    def plan_on(self, day: date) -> Plan:
        """The last plan that started on or before `day`. Days before the first plan use the first."""
        current = self.plans[0]
        for plan in self.plans:
            if plan.effective_from <= day:
                current = plan
            else:
                break
        return current


def _empty_cell() -> dict[str, float]:
    return {"kwh": 0.0, "cost": 0.0}


class UsageLedger:
    """Priced usage per source. Survives restarts via to_dict().

    Layout:
      days[source][YYYY-MM-DD][band] = {"kwh", "cost"}   (pruned after KEEP_DAYS)
      totals[source] = {"kwh", "cost"}                     (never pruned)
      fixed_days[YYYY-MM-DD] = daily charge booked that day
    """

    def __init__(self, data: dict | None = None) -> None:
        data = data or {}
        self.last_seen: dict[str, float] = {
            source: float(value) for source, value in data.get("last_seen", {}).items()
        }
        self.days: dict[str, dict[str, dict[str, dict[str, float]]]] = {
            source: {
                day: {
                    band: {"kwh": float(cell["kwh"]), "cost": float(cell["cost"])}
                    for band, cell in bands.items()
                }
                for day, bands in per_day.items()
            }
            for source, per_day in data.get("days", {}).items()
        }
        self.totals: dict[str, dict[str, float]] = {
            source: {"kwh": float(cell["kwh"]), "cost": float(cell["cost"])}
            for source, cell in data.get("totals", {}).items()
        }
        self.fixed_days: dict[str, float] = {
            day: float(amount) for day, amount in data.get("fixed_days", {}).items()
        }
        # highest averaging block seen per month: "YYYY-MM" -> {"kw": float, "at": iso start}
        self.demand_peaks: dict[str, dict[str, object]] = {
            month: {"kw": float(peak["kw"]), "at": str(peak["at"])}
            for month, peak in data.get("demand_peaks", {}).items()
        }

    def to_dict(self) -> dict:
        return {
            "last_seen": dict(self.last_seen),
            "days": {
                source: {
                    day: {band: dict(cell) for band, cell in bands.items()}
                    for day, bands in per_day.items()
                }
                for source, per_day in self.days.items()
            },
            "totals": {source: dict(cell) for source, cell in self.totals.items()},
            "fixed_days": dict(self.fixed_days),
            "demand_peaks": {m: dict(p) for m, p in self.demand_peaks.items()},
        }

    def demand_estimates(self) -> dict[str, float]:
        return {month: float(peak["kw"]) for month, peak in self.demand_peaks.items()}

    def merge_demand_peaks(self, found: dict[str, tuple[float, datetime]]) -> set[str]:
        """Keep the higher of the stored and the newly found peak. Returns the months that rose."""
        changed: set[str] = set()
        for month, (kw, at) in found.items():
            known = self.demand_peaks.get(month)
            if known is None or kw > float(known["kw"]) + 1e-9:
                self.demand_peaks[month] = {"kw": round(kw, 4), "at": at.isoformat()}
                changed.add(month)
        return changed

    def reprice_fixed_days(self, months: set[str], amount_for: Callable[[date], float]) -> int:
        """Re-book the daily charge of every kept day in `months` (used when a demand estimate
        rises, so each day of the month carries the same demand charge). Returns days changed."""
        changed = 0
        for key in list(self.fixed_days):
            if key[:7] not in months:
                continue
            new = amount_for(date.fromisoformat(key))
            delta = new - self.fixed_days[key]
            if abs(delta) > 1e-12:
                self.fixed_days[key] = new
                self.totals.setdefault(FIXED_KEY, _empty_cell())["cost"] += delta
                changed += 1
        return changed

    def add_energy(self, source: str, day: date, band: str, kwh: float, price: float) -> None:
        """Add kWh that were priced at `price` per kWh (already GST-adjusted if needed)."""
        cost = kwh * price
        cell = self.days.setdefault(source, {}).setdefault(day.isoformat(), {}).setdefault(
            band, _empty_cell()
        )
        cell["kwh"] += kwh
        cell["cost"] += cost
        total = self.totals.setdefault(source, _empty_cell())
        total["kwh"] += kwh
        total["cost"] += cost

    def record(
        self, source: str, value: float, when: datetime, pricer: Callable[[datetime], tuple[str, float]]
    ) -> float:
        """Price the increase in a total_increasing reading at `when`.

        `pricer(when)` returns (band name, price per kWh) for the plan in force then.
        Returns the kWh added. The first reading only sets the baseline.
        """
        previous = self.last_seen.get(source)
        self.last_seen[source] = value
        if previous is None:
            return 0.0
        delta = value - previous if value >= previous else value  # meter reset
        if delta <= 0:
            return 0.0
        band_name, price = pricer(when)
        self.add_energy(source, when.date(), band_name, delta, price)
        return delta

    def ensure_fixed_through(self, today: date, amount_for: Callable[[date], float]) -> int:
        """Book the daily charge for every day up to `today` that has not been booked yet.

        On the first run this starts at the 1st of the current month. After that it fills
        any gap since the last booked day, so days HA was off still carry their charge.
        Returns how many days were booked.
        """
        if self.fixed_days:
            start = max(date.fromisoformat(d) for d in self.fixed_days) + timedelta(days=1)
        else:
            start = date(today.year, today.month, 1)
        booked = 0
        day = start
        while day <= today:
            key = day.isoformat()
            if key not in self.fixed_days:
                amount = amount_for(day)
                self.fixed_days[key] = amount
                self.totals.setdefault(FIXED_KEY, _empty_cell())["cost"] += amount
                booked += 1
            day += timedelta(days=1)
        return booked

    def prune(self, today: date) -> None:
        cutoff = (today - timedelta(days=KEEP_DAYS)).isoformat()
        for per_day in self.days.values():
            for day in [d for d in per_day if d < cutoff]:
                del per_day[day]
        for day in [d for d in self.fixed_days if d < cutoff]:
            del self.fixed_days[day]

    def lifetime_cost(self, source: str) -> float:
        return self.totals.get(source, _empty_cell())["cost"]


def book_hourly(ledger: "UsageLedger", source: str, hours: Iterable[tuple[datetime, float]],
                pricer: Callable[[datetime], tuple[str, float]]) -> float:
    """Book (hour, kWh) pairs at the price in force for each hour. Returns total kWh booked."""
    total = 0.0
    for when, kwh in hours:
        if kwh <= 0:
            continue
        band_name, price = pricer(when)
        ledger.add_energy(source, when.date(), band_name, kwh, price)
        total += kwh
    return total


def book_export_day(ledger: "UsageLedger", source: str, day: date, total_kwh: float, plan: "Plan") -> None:
    """Credit one day's export under a plan with a daily cap: the first `cap` kWh at the band
    rate (step 1), anything above at the over-cap rate (step 2)."""
    if total_kwh <= 0 or plan.export_schedule is None:
        return
    step1_rate = plan.export_schedule.band_at(12).rate
    kwh1 = min(total_kwh, plan.export_daily_cap)
    kwh2 = max(total_kwh - plan.export_daily_cap, 0.0)
    ledger.add_energy(source, day, "fit_step_1", kwh1, step1_rate)
    if kwh2 > 0:
        ledger.add_energy(source, day, "fit_step_2", kwh2, plan.export_over_cap_rate)


def book_fixed_range(ledger: "UsageLedger", first: date, last: date,
                     amount_for: Callable[[date], float]) -> int:
    """Book the daily charge for every day from `first` to `last` inclusive, once per day."""
    booked = 0
    day = first
    while day <= last:
        key = day.isoformat()
        if key not in ledger.fixed_days:
            amount = amount_for(day)
            ledger.fixed_days[key] = amount
            ledger.totals.setdefault(FIXED_KEY, _empty_cell())["cost"] += amount
            booked += 1
        day += timedelta(days=1)
    return booked


def block_peaks(
    slots: Iterable[tuple[datetime, float]],
    *,
    start_hour: int,
    end_hour: int,
    block_minutes: int,
    slot_minutes: int = 5,
) -> dict[str, tuple[float, datetime]]:
    """Highest average kW over clock-aligned blocks inside a daily window, per month.

    `slots` are (slot start, kWh used in the slot). Slots are grouped into blocks that start on
    the clock (a 30-minute block starts at :00 or :30). A block counts only when it lies wholly
    inside the window and every slot in it is present, so a gap can't hide or invent a peak.
    """
    if block_minutes < slot_minutes or block_minutes % slot_minutes or not (0 <= start_hour < end_hour <= 24):
        return {}
    per_block = block_minutes // slot_minutes
    lo, hi = start_hour * 60, end_hour * 60
    blocks: dict[datetime, dict[datetime, float]] = {}
    for start, kwh in slots:
        minute = start.hour * 60 + start.minute
        first = minute - minute % block_minutes
        if first < lo or first + block_minutes > hi:
            continue
        block_start = start.replace(hour=first // 60, minute=first % 60, second=0, microsecond=0)
        blocks.setdefault(block_start, {})[start] = kwh
    peaks: dict[str, tuple[float, datetime]] = {}
    for block_start, members in blocks.items():
        if len(members) != per_block:
            continue
        kw = sum(members.values()) * 60.0 / block_minutes
        month = block_start.strftime("%Y-%m")
        if month not in peaks or kw > peaks[month][0]:
            peaks[month] = (kw, block_start)
    return peaks


def _month_days(today: date) -> list[str]:
    return [date(today.year, today.month, d).isoformat() for d in range(1, today.day + 1)]


def _cost(ledger: UsageLedger, source: str, days: Iterable[str]) -> float:
    per_day = ledger.days.get(source, {})
    return sum(cell["cost"] for day in days for cell in per_day.get(day, {}).values())


def _fixed(ledger: UsageLedger, days: Iterable[str]) -> float:
    return sum(ledger.fixed_days.get(day, 0.0) for day in days)


def band_kwh(ledger: UsageLedger, source: str, today: date, scope: str) -> dict[str, float]:
    """kWh per band for today ("today") or the month to date ("month")."""
    days = [today.isoformat()] if scope == "today" else _month_days(today)
    totals: dict[str, float] = {}
    per_day = ledger.days.get(source, {})
    for day in days:
        for band, cell in per_day.get(day, {}).items():
            totals[band] = totals.get(band, 0.0) + cell["kwh"]
    return totals


def summarize(ledger: UsageLedger, today: date) -> dict[str, float]:
    """Import, export and net cost for today and the month to date (daily charges included)."""
    today_key = [today.isoformat()]
    month_keys = _month_days(today)

    import_today = _cost(ledger, "import", today_key) + _fixed(ledger, today_key)
    import_month = _cost(ledger, "import", month_keys) + _fixed(ledger, month_keys)
    export_today = _cost(ledger, "export", today_key)
    export_month = _cost(ledger, "export", month_keys)

    return {
        "import_today": round(import_today, 2),
        "import_month": round(import_month, 2),
        "export_today": round(export_today, 2),
        "export_month": round(export_month, 2),
        "net_today": round(import_today - export_today, 2),
        "net_month": round(import_month - export_month, 2),
    }


def device_cost(ledger: UsageLedger, source: str, today: date) -> tuple[float, float]:
    """Energy-only cost today and month to date for one tracked sensor."""
    return (
        round(_cost(ledger, source, [today.isoformat()]), 2),
        round(_cost(ledger, source, _month_days(today)), 2),
    )


def current_tariff(timeline: Timeline, when: datetime) -> tuple[Band, float, int]:
    """Active import band, its GST-inclusive rate, and the hour the next band starts."""
    plan = timeline.plan_on(when.date())
    band = plan.import_schedule.band_at(when.hour)
    rate = band.rate * plan.import_factor
    return band, rate, plan.import_schedule.next_change(when.hour)
