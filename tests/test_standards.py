async def test_in_flight_demand_query_cannot_update_an_unloaded_runtime(
    hass, monkeypatch
):
    entry = await _setup(hass)
    runtime = entry.runtime_data
    entered, release = asyncio.Event(), asyncio.Event()

    async def query(*args):
        entered.set()
        await release.wait()
        return []

    recorder = SimpleNamespace(async_add_executor_job=AsyncMock(side_effect=query))
    monkeypatch.setattr(
        "custom_components.power_bill.runtime.get_instance", lambda hass_: recorder
    )
    scanning = asyncio.create_task(runtime._async_scan_demand(1, reprice=True))
    await entered.wait()
    stopping = asyncio.create_task(runtime.async_stop())
    await asyncio.sleep(0)
    assert not stopping.done()
    release.set()
    await asyncio.gather(scanning, stopping)
    assert runtime.ledger.demand_peaks == {}
    assert runtime._stopping and not runtime._unsubs


