async def _defensive_submit(manager, result, data):
    """Check selector rejection as well as defensive handling without the schema."""
    with pytest.raises(InvalidData):
        await manager.async_configure(result["flow_id"], data)
    # Exercise the active step's validation for callers bypassing the selector.
    # The corrected input below still completes through the real flow manager.
    flow = manager._progress[result["flow_id"]]
    return await getattr(flow, f"async_step_{result['step_id']}")(data)


