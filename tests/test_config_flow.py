def _bands(prefix="import", **changes):
    return {
        f"{prefix}_band_1_name": "flat",
        f"{prefix}_band_1_start": 0,
        f"{prefix}_band_1_end": 24,
        f"{prefix}_band_1_rate": 0.25,
        **changes,
    }


def _plan(**changes):
    return {
        "effective_from": "2000-01-01",
        "import_bands": [{"name": "flat", "start": 0, "end": 24, "rate": 0.25}],
        "export_bands": [{"name": "fit", "start": 0, "end": 24, "rate": 0.1}],
        **{key: value for key, value in CHARGES.items() if key != "tracked_devices"},
        **changes,
    }


async def _start(hass, *, export=False):
    result = await hass.config_entries.flow.async_init(
        DOMAIN, context={"source": SOURCE_USER}
    )
    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "user"
    data = {"provider": "  Example  ", "import_entity": IMPORT}
    if export:
        data["export_entity"] = EXPORT
    return await hass.config_entries.flow.async_configure(result["flow_id"], data)


async def _finish(hass, result):
    if result["step_id"] == "import_bands":
        result = await hass.config_entries.flow.async_configure(
            result["flow_id"], _bands()
        )
    if result["step_id"] == "export_bands":
        result = await hass.config_entries.flow.async_configure(
            result["flow_id"], _bands("export")
        )
    assert result["step_id"] == "charges"
    result = await hass.config_entries.flow.async_configure(result["flow_id"], CHARGES)
    assert result["type"] is FlowResultType.CREATE_ENTRY
    await hass.async_block_till_done()
    return result


async def _entry(hass, *, plans=None, export=True, legacy=False):
    data = {"import_entity": IMPORT}
    if export:
        data["export_entity"] = EXPORT
    options = {"provider": "Example", "tracked_devices": [DEVICE]}
    if legacy:
        data.update(_plan())
        data.pop("effective_from")
        data["provider"] = options.pop("provider")
    else:
        options["plans"] = plans or [_plan()]
    data, options = prepare_sources(hass, data, options)
    entry = MockConfigEntry(
        domain=DOMAIN,
        title="Example",
        version=1,
        minor_version=3,
        unique_id=f"{IMPORT}|{EXPORT if export else ''}",
        data=data,
        options=options,
    )
    entry.add_to_hass(hass)
    return entry


