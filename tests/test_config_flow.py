def _register_sources(hass):
    registry = er.async_get(hass)
    for entity_id in (IMPORT, EXPORT, DEVICE):
        hass.states.async_remove(entity_id)
        entity = registry.async_get_or_create(
            "sensor",
            "flow_test",
            f"original_{entity_id}",
            suggested_object_id=entity_id.split(".", 1)[1],
        )
        assert entity.entity_id == entity_id
        hass.states.async_set(entity_id, "100", ATTRS)
    return registry


def _rename_source(hass, registry, entity_id, new_entity_id):
    registry.async_update_entity(entity_id, new_entity_id=new_entity_id)
    hass.states.async_remove(entity_id)
    hass.states.async_set(new_entity_id, "100", ATTRS)


