def _tariff():
    return {
        "provider": "Identity",
        "import_bands": [{"name": "flat", "start": 0, "end": 24, "rate": 0.2}],
        "daily_supply": 0,
        "daily_membership": 0,
        "rates_include_gst": True,
        "tracked_devices": [DEVICE],
    }


async def _setup(hass, *, legacy=False):
    data = {"import_entity": IMPORT}
    options = _tariff()
    if legacy:
        data.update(options)
        options = {}
    entry = MockConfigEntry(
        domain=DOMAIN,
        title="Identity",
        data=data,
        options=options,
        version=1,
        minor_version=1 if legacy else 2,
    )
    entry.add_to_hass(hass)
    legacy_child = None
    if legacy:
        registry = er.async_get(hass)
        registry.async_get_or_create(
            "sensor",
            DOMAIN,
            f"{entry.entry_id}_device_identity_device_today",
            config_entry=entry,
            suggested_object_id="my_old_ev_bill_today",
        )
        legacy_child = registry.async_get_or_create(
            "sensor",
            DOMAIN,
            f"{entry.entry_id}_device_identity_device_total",
            config_entry=entry,
            suggested_object_id="my_old_ev_bill",
        )
        legacy_child = registry.async_update_entity(
            legacy_child.entity_id, name="My original EV bill", icon="mdi:car-electric"
        )
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()
    return entry, legacy_child


def _total_entity(hass, entry, entity_id):
    key = entry.runtime_data.device_sensor_key(entity_id)
    unique_id = f"{entry.entry_id}_{key}_total"
    registry = er.async_get(hass)
    child_id = registry.async_get_entity_id("sensor", DOMAIN, unique_id)
    assert child_id is not None
    return registry.async_get(child_id)


async def _rename_meter(hass):
    registry = er.async_get(hass)
    registry.async_update_entity(DEVICE, new_entity_id=RENAMED)
    state = hass.states.get(DEVICE)
    hass.states.async_remove(DEVICE)
    hass.states.async_set(RENAMED, state.state, state.attributes)
    await hass.async_block_till_done()


@pytest.mark.parametrize("legacy", [False, True])
async def test_source_rename_keeps_customized_cost_entity_and_usage(hass, legacy):
    """A renamed meter retains the same cost entity, customization and pending usage."""
    entry, legacy_child = await _setup(hass, legacy=legacy)
    runtime = entry.runtime_data
    child = _total_entity(hass, entry, DEVICE)
    if legacy_child:
        assert child.id == legacy_child.id
        assert child.unique_id == legacy_child.unique_id
        assert child.name == "My original EV bill"
    registry = er.async_get(hass)
    customized = registry.async_update_entity(
        child.entity_id,
        new_entity_id="sensor.my_ev_spend",
        name="My EV spend",
        icon="mdi:car-electric",
    )
    await hass.async_block_till_done()
    identities_before = {
        entity.unique_id: (entity.id, entity.entity_id)
        for entity in er.async_entries_for_config_entry(registry, entry.entry_id)
    }
    if legacy:
        assert (
            identities_before[f"{entry.entry_id}_device_identity_device_today"][1]
            == "sensor.my_old_ev_bill_today"
        )
    hass.states.async_set(DEVICE, "101", ATTRS)
    await hass.async_block_till_done()
    old_record = source_record(entry.data, DEVICE)
    ledger_key = old_record["ledger_key"]
    pending = copy.deepcopy(runtime._pending_energy[ledger_key])
    assert runtime.lifetime_device(DEVICE) == pytest.approx(0.2)

    await _rename_meter(hass)

    assert entry.runtime_data is not runtime
    assert runtime._stopping
    assert entry.options["tracked_devices"] == [RENAMED]
    current = _total_entity(hass, entry, RENAMED)
    assert current.id == customized.id
    assert current.unique_id == customized.unique_id
    assert current.entity_id == "sensor.my_ev_spend"
    assert current.name == "My EV spend"
    assert current.icon == "mdi:car-electric"
    assert identities_before == {
        entity.unique_id: (entity.id, entity.entity_id)
        for entity in er.async_entries_for_config_entry(registry, entry.entry_id)
    }
    assert source_record(entry.data, RENAMED)["ledger_key"] == ledger_key
    assert entry.runtime_data._pending_energy[ledger_key] == pending
    assert entry.runtime_data.lifetime_device(RENAMED) == pytest.approx(0.2)
    assert entry.runtime_data.source_available(RENAMED)
    assert hass.states.get(current.entity_id).state == "0.2"
    hass.states.async_set(RENAMED, "102", ATTRS)
    await hass.async_block_till_done()
    assert entry.runtime_data.lifetime_device(RENAMED) == pytest.approx(0.4)
    assert entry.runtime_data.device_costs(RENAMED) == pytest.approx((0.4, 0.4))


async def test_source_rename_while_unloaded_resolves_registry_identity(hass):
    """Registry identity resolves a meter renamed while the contract was stopped."""
    entry, _ = await _setup(hass)
    hass.states.async_set(DEVICE, "101", ATTRS)
    await hass.async_block_till_done()
    child = _total_entity(hass, entry, DEVICE)
    record = dict(source_record(entry.data, DEVICE))
    assert await hass.config_entries.async_unload(entry.entry_id)
    await hass.async_block_till_done()
    await _rename_meter(hass)

    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()
    assert entry.options["tracked_devices"] == [RENAMED]
    updated = source_record(entry.data, RENAMED)
    assert updated["registry_id"] == record["registry_id"]
    assert updated["sensor_key"] == record["sensor_key"]
    assert updated["ledger_key"] == record["ledger_key"]
    assert _total_entity(hass, entry, RENAMED).id == child.id
    assert entry.runtime_data.lifetime_device(RENAMED) == pytest.approx(0.2)


async def test_different_registry_source_reusing_old_entity_id_gets_fresh_identity(
    hass,
):
    """A reused entity ID cannot assign one meter's bill and usage to another."""
    entry, _ = await _setup(hass)
    hass.states.async_set(DEVICE, "101", ATTRS)
    await hass.async_block_till_done()
    original_child = _total_entity(hass, entry, DEVICE)
    original_record = dict(source_record(entry.data, DEVICE))
    await _rename_meter(hass)
    registry = er.async_get(hass)
    replacement = registry.async_get_or_create(
        "sensor", "test", "a-different-meter", suggested_object_id="identity_device"
    )
    assert replacement.entity_id == DEVICE
    assert replacement.id != original_record["registry_id"]
    hass.states.async_set(DEVICE, "10", ATTRS)
    hass.config_entries.async_update_entry(
        entry, options={**entry.options, "tracked_devices": [RENAMED, DEVICE]}
    )
    assert await hass.config_entries.async_reload(entry.entry_id)
    await hass.async_block_till_done()

    new_record = source_record(entry.data, DEVICE)
    assert new_record["registry_id"] == replacement.id
    assert new_record["sensor_key"] != original_record["sensor_key"]
    assert new_record["ledger_key"] != original_record["ledger_key"]
    assert _total_entity(hass, entry, RENAMED).id == original_child.id
    assert _total_entity(hass, entry, DEVICE).id != original_child.id
    assert entry.runtime_data.lifetime_device(RENAMED) == pytest.approx(0.2)
    assert entry.runtime_data.lifetime_device(DEVICE) == 0
    hass.states.async_set(DEVICE, "unavailable", ATTRS)
    await hass.async_block_till_done()
    assert not entry.runtime_data.source_available(DEVICE)
    assert entry.runtime_data.source_available(RENAMED)
    assert hass.states.get(_total_entity(hass, entry, DEVICE).entity_id).state == (
        "unavailable"
    )
    assert hass.states.get(original_child.entity_id).state == "0.2"
    hass.states.async_set(DEVICE, "10", ATTRS)
    await hass.async_block_till_done()
    assert entry.runtime_data.source_available(DEVICE)
    hass.states.async_set(DEVICE, "11", ATTRS)
    await hass.async_block_till_done()
    assert entry.runtime_data.lifetime_device(DEVICE) == pytest.approx(0.2)
    assert entry.runtime_data.lifetime_device(RENAMED) == pytest.approx(0.2)


@pytest.mark.parametrize("unload", [False, True])
async def test_removed_registry_source_cannot_give_its_usage_to_replacement(
    hass, unload
):
    """A deleted registry object is distinct from a replacement at the same entity ID."""
    entry, _ = await _setup(hass)
    hass.states.async_set(DEVICE, "101", ATTRS)
    await hass.async_block_till_done()
    original_runtime = entry.runtime_data
    original = dict(source_record(entry.data, DEVICE))
    original_child = _total_entity(hass, entry, DEVICE)
    if unload:
        assert await hass.config_entries.async_unload(entry.entry_id)
        await hass.async_block_till_done()

    registry = er.async_get(hass)
    registry.async_remove(DEVICE)
    hass.states.async_remove(DEVICE)
    replacement = registry.async_get_or_create(
        "sensor",
        "test",
        "replacement-after-deletion",
        suggested_object_id="identity_device",
    )
    assert replacement.entity_id == DEVICE
    hass.states.async_set(DEVICE, "10", ATTRS)
    if unload:
        assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()

    assert entry.runtime_data is not original_runtime
    assert original_runtime._stopping
    assert original_runtime.ledger.lifetime_cost(original["ledger_key"]) == (
        pytest.approx(0.2)
    )
    record = source_record(entry.data, DEVICE)
    assert record["registry_id"] == replacement.id
    assert record["registry_id"] != original["registry_id"]
    assert record["sensor_key"] != original["sensor_key"]
    assert record["ledger_key"] != original["ledger_key"]
    assert _total_entity(hass, entry, DEVICE).unique_id != original_child.unique_id
    assert entry.runtime_data.lifetime_device(DEVICE) == 0
    hass.states.async_set(DEVICE, "11", ATTRS)
    await hass.async_block_till_done()
    assert entry.runtime_data.lifetime_device(DEVICE) == pytest.approx(0.2)


async def test_unregistered_source_binds_registry_identity_without_changing_keys(hass):
    """A source gaining registry support keeps the cost entities already created for it."""
    registry = er.async_get(hass)
    registry.async_remove(DEVICE)
    entry, _ = await _setup(hass)
    runtime = entry.runtime_data
    before = dict(source_record(entry.data, DEVICE))
    assert before["registry_id"] is None
    child = _total_entity(hass, entry, DEVICE)
    hass.states.async_set(DEVICE, "101", ATTRS)
    await hass.async_block_till_done()
    assert runtime.lifetime_device(DEVICE) == pytest.approx(0.2)

    # An entity platform registers its entity before writing its first state.
    hass.states.async_remove(DEVICE)
    registered = registry.async_get_or_create(
        "sensor",
        "test",
        "newly-registered-meter",
        suggested_object_id="identity_device",
    )
    assert registered.entity_id == DEVICE
    hass.states.async_set(DEVICE, "101", ATTRS)
    await hass.async_block_till_done()
    bound = source_record(entry.data, DEVICE)
    assert bound["registry_id"] == registered.id
    assert bound["sensor_key"] == before["sensor_key"]
    assert bound["ledger_key"] == before["ledger_key"]
    assert entry.runtime_data is runtime
    assert _total_entity(hass, entry, DEVICE).id == child.id

    await _rename_meter(hass)
    assert entry.options["tracked_devices"] == [RENAMED]
    assert _total_entity(hass, entry, RENAMED).id == child.id
    assert entry.runtime_data.lifetime_device(RENAMED) == pytest.approx(0.2)
