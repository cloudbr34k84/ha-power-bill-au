async def test_demand_charge_is_booked_per_day_from_the_bill_kw(
    hass: HomeAssistant,
) -> None:
    """Demand is $/kW/day on the billed kW: 14.30 kW for November 2024 is $79.37 on the bill."""
    plan = Plan(
        effective_from=date(2000, 1, 1),
        import_schedule=Schedule([Band(name="flat", start=0, end=24, rate=0.22)]),
        daily_supply=1.09,
        daily_membership=0.5422,
        demand_rate=0.185,
        demand_kw={"2024-11": 14.30},
    )
    total = sum(plan.charge_per_day(date(2024, 11, d)) for d in range(1, 31)) - 30 * (
        1.09 + 0.5422
    )
    assert abs(total - 79.37) < 0.05
    assert plan.demand_per_day(date(2024, 12, 1)) == 0.0


