async def test_a_higher_block_later_reprices_the_month_and_survives_a_restart(
    hass: HomeAssistant, freezer, monkeypatch
) -> None:
    entry, state = await _setup_estimating(
        hass, freezer, monkeypatch, _five_minute_rows(0.75)
    )
    rt = entry.runtime_data
    before = rt.lifetime_import()
    state["rows"] = _five_minute_rows(1.0)  # 12 kW
    await rt._async_scan_demand(1, reprice=True)
    assert round(rt.demand_status()["kw"], 6) == 12.0
    # 7 kept days of November (1st to 7th) each rise by 3 kW x $0.20
    assert rt.lifetime_import() == pytest.approx(before + 7 * 3.0 * 0.2, abs=0.02)
    # a later, lower scan never lowers it
    state["rows"] = _five_minute_rows(0.5)
    await rt._async_scan_demand(1, reprice=True)
    assert round(rt.demand_status()["kw"], 6) == 12.0

    # restart with no statistics to look at: the saved peak is still there
    state["rows"] = []
    assert await hass.config_entries.async_reload(entry.entry_id)
    await hass.async_block_till_done()
    rt = entry.runtime_data
    assert round(rt.demand_status()["kw"], 6) == 12.0
    assert rt.ledger.fixed_days["2026-11-03"] == pytest.approx(1.0 + 12.0 * 0.2)


