@pytest.mark.parametrize("label_key,export", [("name", False), ("provider", True)])
async def test_legacy_contract_migration_keeps_settings_usage_and_sensor_ids(
    hass, label_key, export
):
    """An upgrade preserves effective options and the identity of a used contract."""
    data = {label_key: "Bronze", "import_entity": IMPORT, **_tariff()}
    if export:
        data.update(
            export_entity=EXPORT,
            export_bands=[{"name": "fit", "start": 0, "end": 24, "rate": 0.1}],
        )
    unique_id = f"{IMPORT}|{EXPORT if export else ''}"
    entry = MockConfigEntry(
        domain=DOMAIN,
        title="Bronze",
        unique_id=unique_id,
        data=data,
        options={"daily_supply": 1},
        version=1,
        minor_version=1,
    )
    entry.add_to_hass(hass)
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()

    assert entry.minor_version == 3
    assert {key: value for key, value in entry.data.items() if key != "sources"} == {
        "import_entity": IMPORT,
        **({"export_entity": EXPORT} if export else {}),
    }
    assert entry.options[label_key] == "Bronze"
    assert entry.options["daily_supply"] == 1
    assert entry.options["import_bands"] == data["import_bands"]
    assert entry.unique_id == unique_id
    assert entry.title == "Bronze"

    hass.states.async_set(IMPORT, "101", ATTRS)
    await hass.async_block_till_done()
    assert entry.runtime_data.lifetime_import() == pytest.approx(1.2)
    registry = er.async_get(hass)
    entities_before = {
        entity.unique_id: entity.entity_id
        for entity in er.async_entries_for_config_entry(registry, entry.entry_id)
    }
    assert "sensor.bronze_current_tariff" in entities_before.values()
    assert hass.states.get("sensor.bronze_import_cost_total").state == "1.2"

    assert await hass.config_entries.async_reload(entry.entry_id)
    await hass.async_block_till_done()
    assert entry.runtime_data.lifetime_import() == pytest.approx(1.2)
    assert entities_before == {
        entity.unique_id: entity.entity_id
        for entity in er.async_entries_for_config_entry(registry, entry.entry_id)
    }
    assert entry.unique_id == unique_id


@pytest.mark.parametrize("minor_version", [3, 4])
async def test_current_or_newer_minor_schema_is_left_intact(hass, minor_version):
    """Reloads and downgrades cannot overwrite settings in an already migrated entry."""
    entry = MockConfigEntry(
        domain=DOMAIN,
        version=1,
        minor_version=minor_version,
        data={"import_entity": IMPORT},
        options={"provider": "Bronze", **_tariff()},
    )
    entry.add_to_hass(hass)
    before = copy.deepcopy(entry.as_dict())
    assert await async_migrate_entry(hass, entry)
    assert entry.as_dict() == before


async def test_newer_major_schema_is_rejected_without_rewriting_settings(hass):
    entry = MockConfigEntry(
        domain=DOMAIN, version=2, data={"future_connection": IMPORT}
    )
    entry.add_to_hass(hass)
    before = copy.deepcopy(entry.as_dict())
    assert not await async_migrate_entry(hass, entry)
    assert entry.as_dict() == before


async def test_invalid_saved_tariff_reports_permanent_setup_failure(hass):
    """A broken tariff is reported as an error rather than retried indefinitely."""
    tariff = _tariff()
    tariff["import_bands"][0]["rate"] = -1
    entry = MockConfigEntry(
        domain=DOMAIN,
        version=1,
        minor_version=2,
        data={"import_entity": IMPORT},
        options={"provider": "Bronze", **tariff},
    )
    entry.add_to_hass(hass)
    assert not await hass.config_entries.async_setup(entry.entry_id)
    assert entry.state is ConfigEntryState.SETUP_ERROR
    assert "Invalid tariff configuration" in entry.reason
